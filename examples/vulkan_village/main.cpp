struct V3
{
	float x = 0.f, y = 0.f, z = 0.f;
};
V3 operator+(V3 a, V3 b) { return {a.x + b.x, a.y + b.y, a.z + b.z}; }
V3 operator-(V3 a, V3 b) { return {a.x - b.x, a.y - b.y, a.z - b.z}; }
V3 operator-(V3 a) { return {-a.x, -a.y, -a.z}; }
V3 operator*(V3 a, float s) { return {a.x * s, a.y * s, a.z * s}; }
float Dot(V3 a, V3 b) { return a.x * b.x + a.y * b.y + a.z * b.z; }
V3 Cross(V3 a, V3 b) { return {a.y * b.z - a.z * b.y, a.z * b.x - a.x * b.z, a.x * b.y - a.y * b.x}; }
float Length(V3 a) { return std::sqrt(Dot(a, a)); }
V3 Normalize(V3 a)
{
	const float l = Length(a);
	return l > 1e-8f ? a * (1.f / l) : V3{0.f, 1.f, 0.f};
}
float Clamp(float v, float a, float b) { return v < a ? a : (v > b ? b : v); }
float Mix(float a, float b, float t) { return a + (b - a) * t; }
float Smooth(float e0, float e1, float x)
{
	const float t = Clamp((x - e0) / (e1 - e0), 0.f, 1.f);
	return t * t * (3.f - 2.f * t);
}

uint32_t Hash(uint32_t x)
{
	x ^= x >> 16; x *= 0x7feb352du; x ^= x >> 15; x *= 0x846ca68bu; x ^= x >> 16;
	return x;
}
float Hash2(int x, int y) { return (float)(Hash((uint32_t)x * 73856093u ^ (uint32_t)y * 19349663u) & 0xFFFFFF) / 16777215.f; }
float Hash3(int x, int y, int z) { return (float)(Hash((uint32_t)x * 73856093u ^ (uint32_t)y * 19349663u ^ (uint32_t)z * 83492791u) & 0xFFFFFF) / 16777215.f; }

struct Rng
{
	uint32_t s;
	explicit Rng(uint32_t seed) : s(Hash(seed * 2654435761u + 1u)) {}
	float F() { s = Hash(s + 0x9e3779b9u); return (float)(s & 0xFFFFFF) / 16777215.f; }
	float R(float a, float b) { return a + (b - a) * F(); }
	int I(int n) { return std::min(n - 1, (int)(F() * (float)n)); }
	bool P(float p) { return F() < p; }
};

float ValueNoise(float x, float y)
{
	const int ix = (int)std::floor(x), iy = (int)std::floor(y);
	float fx = x - (float)ix, fy = y - (float)iy;
	fx = fx * fx * (3.f - 2.f * fx);
	fy = fy * fy * (3.f - 2.f * fy);
	const float a = Hash2(ix, iy), b = Hash2(ix + 1, iy), c = Hash2(ix, iy + 1), d = Hash2(ix + 1, iy + 1);
	return a + (b - a) * fx + (c - a) * fy + (a - b - c + d) * fx * fy;
}

float Fbm(float x, float y, int octaves)
{
	float sum = 0.f, amplitude = 0.5f;
	for (int o = 0; o < octaves; ++o)
	{
		sum += amplitude * ValueNoise(x, y);
		x = x * 2.03f + 17.f;
		y = y * 2.03f - 9.f;
		amplitude *= 0.5f;
	}
	return sum;
}

float ValueNoise3(float x, float y, float z)
{
	const int ix = (int)std::floor(x), iy = (int)std::floor(y), iz = (int)std::floor(z);
	float fx = x - (float)ix, fy = y - (float)iy, fz = z - (float)iz;
	fx = fx * fx * (3.f - 2.f * fx);
	fy = fy * fy * (3.f - 2.f * fy);
	fz = fz * fz * (3.f - 2.f * fz);
	float v[2];
	for (int k = 0; k < 2; ++k)
	{
		const float a = Hash3(ix, iy, iz + k), b = Hash3(ix + 1, iy, iz + k);
		const float c = Hash3(ix, iy + 1, iz + k), d = Hash3(ix + 1, iy + 1, iz + k);
		v[k] = Mix(Mix(a, b, fx), Mix(c, d, fx), fy);
	}
	return Mix(v[0], v[1], fz);
}

