// HRL example: a stylized Mediterranean fishing village (native Vulkan backend).
//
//   * tall pastel houses stacked in an amphitheatre around a small cove: green
//     shutters, terracotta / slate tile roofs, laundry, flower boxes, shops;
//   * smooth lilac rocks along the water line, a paved piazza with a fountain,
//     a quay, a beach with umbrellas, rowing boats floating in the harbour;
//   * turquoise water whose colour follows the depth of the sea bed, with foam
//     along the shore (custom surface shader);
//   * terraced green hills with round trees, cypresses and umbrella pines
//     (GPU culled foliage);
//   * warm afternoon sun, sky light, ambient occlusion, bloom, colour grading.
//
// Everything is generated by the program: no external resource. The details of
// the buildings (plaster, tiles, stones, cobbles, slats...) are drawn by one
// surface shader from the world position; without the run time shader compiler
// the scene falls back on the built-in material and flat colours.
//
//   hrl_vulkan_village                         opens a window
//   hrl_vulkan_village --screenshot out.png    renders off-screen and writes a PNG
//   options: --size W H   --view 1..5   --rt   --frames N   --no-gi
//            --volumetric-clouds (instead of the stylized cloud meshes)
//
// Controls: right mouse button + mouse to look, W A S D to move, Q / E down /
// up, Shift faster. 1 - 5 viewpoints, R ray traced shadows, P screenshot,
// Escape quits.
