// Smooth rounded boulder: a squashed sphere with soft low frequency bumps.
void AddRock(MeshData& m, V3 center, V3 radii, float yaw, uint32_t seed, int slot)
{
	const float c = std::cos(yaw), s = std::sin(yaw);
	const float ox = (float)(seed % 97) * 3.1f, oz = (float)(seed % 89) * 2.7f;
	const float u = ((float)slot + 0.5f) / (float)kPaletteSlots, v = (float)M_ROCK + 0.5f;
	AddSmoothSphere(m, 14, 22,
		[&](V3 d)
		{
			const float n = ValueNoise3(d.x * 1.3f + ox, d.y * 1.3f, d.z * 1.3f + oz) * 0.32f + ValueNoise3(d.x * 3.f + oz, d.y * 3.f, d.z * 3.f) * 0.08f;
			float k = 0.82f + n;
			V3 p{d.x * radii.x * k, d.y * radii.y * k, d.z * radii.z * k};
			if (p.y < -radii.y * 0.5f) p.y = -radii.y * 0.5f + (p.y + radii.y * 0.5f) * 0.3f; // flattened base
			return center + V3{p.x * c + p.z * s, p.y, -p.x * s + p.z * c};
		},
		[&](V3, float& uu, float& vv) { uu = u; vv = v; });
}

// Rowing boat (gozzo) along +X, bow at +X, origin on the water line.
MeshData MakeBoat(float L, float B, float depth, int hull, uint32_t seed)
{
	MeshData m;
	Rng r(seed);
	const int stations = 16, profile = 10;
	auto halfWidth = [&](float t) { return B * 0.5f * std::pow(std::max(0.f, std::sin(kPi * (0.1f + 0.9f * t))), 0.55f); };
	auto sheer = [&](float t) { const float e = 2.f * t - 1.f; return 0.35f + 0.22f * e * e + 0.12f * std::max(0.f, e); };
	auto keel = [&](float t) { return depth * (0.55f + 0.45f * std::sin(kPi * t)); };
	auto hullPoint = [&](float t, float phi)
	{
		const float x = (t - 0.5f) * L;
		const float w = halfWidth(t), sp = std::max(0.f, std::sin(phi));
		return V3{x, sheer(t) - keel(t) * std::pow(sp, 0.7f), w * std::cos(phi)};
	};
	// Hull surface (two sided material): smooth normals over the grid.
	const HRL_uint base = (HRL_uint)m.vertices.size();
	std::vector<V3> pos, nrm;
	for (int i = 0; i <= stations; ++i)
		for (int j = 0; j <= profile; ++j) pos.push_back(hullPoint((float)i / stations, (float)j / profile * kPi));
	nrm.resize(pos.size());
	std::vector<HRL_uint> idx;
	for (int i = 0; i < stations; ++i)
		for (int j = 0; j < profile; ++j)
		{
			const HRL_uint a = (HRL_uint)(i * (profile + 1) + j), b2 = a + 1, c = a + profile + 1, d = c + 1;
			idx.insert(idx.end(), {a, c, b2, b2, c, d});
		}
	for (size_t k = 0; k < idx.size(); k += 3)
	{
		const V3 n = Cross(pos[idx[k + 1]] - pos[idx[k]], pos[idx[k + 2]] - pos[idx[k]]);
		for (int j = 0; j < 3; ++j) nrm[idx[k + j]] = nrm[idx[k + j]] + n;
	}
	const float u = ((float)hull + 0.5f) / (float)kPaletteSlots, v = (float)M_PLAIN + 0.5f;
	for (size_t k = 0; k < pos.size(); ++k)
	{
		V3 n = Normalize(nrm[k]);
		// Outwards: away from the centre line.
		if (Dot(n, V3{0.f, pos[k].y - 0.2f, pos[k].z}) < 0.f) n = -n;
		m.vertices.push_back(MakeVertex(pos[k], n, u, v, {1.f, 0.f, 0.f}));
	}
	for (HRL_uint i : idx) m.indices.push_back(base + i);
	// Gunwales, thwarts and a stripe under the rail.
	Builder b{m, Frame{}};
	const int stripe = r.P(0.5f) ? C_BOAT_WHITE : (hull == C_BOAT_WHITE ? C_BOAT_BLUE : C_WOOD);
	for (int i = 0; i < stations; ++i)
	{
		const float t0 = (float)i / stations, t1 = (float)(i + 1) / stations;
		for (float side : {0.f, kPi})
		{
			const V3 p0 = hullPoint(t0, side), p1 = hullPoint(t1, side);
			const float out = side == 0.f ? 1.f : -1.f;
			b.Slab(p0 + V3{0.f, 0.04f, -out * 0.06f}, p1 + V3{0.f, 0.04f, -out * 0.06f}, p1 + V3{0.f, 0.04f, out * 0.03f},
				p0 + V3{0.f, 0.04f, out * 0.03f}, 0.07f, C_WOOD, M_WOOD, M_WOOD);
			const V3 q0 = hullPoint(t0, side == 0.f ? 0.18f : kPi - 0.18f), q1 = hullPoint(t1, side == 0.f ? 0.18f : kPi - 0.18f);
			b.Quad(p0 + V3{0.f, -0.02f, out * 0.012f}, p1 + V3{0.f, -0.02f, out * 0.012f}, q1 + V3{0.f, 0.f, out * 0.012f},
				q0 + V3{0.f, 0.f, out * 0.012f}, {0.f, 0.f, out}, stripe, M_PLAIN);
		}
	}
	for (float t : {0.3f, 0.62f})
	{
		const float w = halfWidth(t) * 0.92f, y = sheer(t) - 0.22f, x = (t - 0.5f) * L;
		b.BoxC({x, y, 0.f}, {0.13f, 0.03f, w}, C_WOOD, M_WOOD);
	}
	// Oars resting inside.
	if (r.P(0.6f)) b.BoxC({0.f, sheer(0.5f) - 0.15f, 0.12f}, {L * 0.36f, 0.025f, 0.03f}, C_WOOD, M_WOOD);
	return m;
}

void AddUmbrella(MeshData& m, V3 base, int color, float tilt)
{
	Builder b{m, Frame{}};
	b.Prism(base, 0.03f, 2.2f, 5, C_TRIM_WHITE, M_PLAIN, false);
	const V3 top = base + V3{tilt, 2.45f, 0.f};
	const int sides = 8;
	const float radius = 1.2f, drop = 0.42f;
	for (int k = 0; k < sides; ++k)
	{
		const float a0 = (float)k / sides * 2.f * kPi, a1 = (float)(k + 1) / sides * 2.f * kPi;
		const V3 p0 = base + V3{tilt + std::cos(a0) * radius, 2.45f - drop, std::sin(a0) * radius};
		const V3 p1 = base + V3{tilt + std::cos(a1) * radius, 2.45f - drop, std::sin(a1) * radius};
		const V3 tri[3] = {top, p0, p1};
		const float am = (a0 + a1) * 0.5f;
		b.Poly(tri, 3, {std::cos(am), 1.f, std::sin(am)}, (k % 2) ? color : C_TRIM_WHITE, M_PLAIN);
		b.Poly(tri, 3, {-std::cos(am), -1.f, -std::sin(am)}, (k % 2) ? color : C_TRIM_WHITE, M_PLAIN);
	}
}

