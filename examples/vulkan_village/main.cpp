// The village is cut in blocks (by angle around the cove) so each mesh can be culled.
void BuildVillage(World& w, MeshData blocks[8])
{
	auto blockOf = [](float theta) { return std::clamp((int)((theta / kPi + 1.f) * 4.f), 0, 7); };
	uint32_t seed = 1000;
	// Rows of houses along the contour lines, facing the cove.
	for (int row = 0; row < 10; ++row)
	{
		const float d = 6.f + (float)row * 8.6f;
		const float maxDeg = VillageEdgeDeg(d);
		float theta = -maxDeg * kPi / 180.f + Hash2(row, 7) * 0.02f;
		while (theta < maxDeg * kPi / 180.f)
		{
			Rng r(seed++);
			const float width = r.R(4.2f, 7.2f);
			const float gap = r.P(0.12f) ? r.R(1.8f, 3.f) : r.R(0.f, 0.25f);
			const float radius = ShoreRadius(theta) + d;
			const float dTheta = (width + gap) / radius;
			const float tc = theta + dTheta * 0.5f;
			theta += dTheta;
			const float deg = tc * 180.f / kPi;
			const float dd = d + r.R(-1.2f, 1.2f);
			V3 front = FromPolar(tc, dd);
			if (InPiazza(front.x, front.z, 2.f)) continue;
			if (BeachMask(deg) > 0.2f && dd < 22.f) continue;
			if (VillageMask(deg) < 0.6f) continue;
			// Face the middle of the cove (a little towards the open sea).
			float fx = kCoveX - front.x, fz = kCoveZ + 30.f - front.z;
			const float yawJitter = r.R(-0.08f, 0.08f);
			const float cj = std::cos(yawJitter), sj = std::sin(yawJitter);
			const float jx = fx * cj - fz * sj, jz = fx * sj + fz * cj;
			front.y = TerrainHeight(front.x, front.z);
			if (front.y < 0.6f) continue;
			HouseParams hp;
			hp.width = width;
			hp.depth = r.R(5.5f, 9.f);
			hp.height = r.R(7.5f, 15.5f) + (r.P(0.15f) ? 3.f : 0.f);
			// Houses on the water front are taller and narrower.
			if (row == 0) hp.height += 2.f;
			BuildHouse(blocks[blockOf(tc)], Frame::Facing(front, jx, jz), hp, seed * 31u);
			++w.houses;
		}
	}
	// Houses around the piazza, at its level (they hide the slope behind it).
	{
		auto line = [&](float x0, float z0, float x1, float z1, float fx, float fz)
		{
			const float len = std::sqrt((x1 - x0) * (x1 - x0) + (z1 - z0) * (z1 - z0));
			for (float t = 0.f; t < len - 3.f;)
			{
				Rng r(seed++);
				const float width = std::min(r.R(4.5f, 6.5f), len - t);
				const float c = (t + width * 0.5f) / len;
				const V3 front{x0 + (x1 - x0) * c, kPiazzaY, z0 + (z1 - z0) * c};
				HouseParams hp;
				hp.width = width;
				hp.depth = r.R(8.f, 10.f);
				hp.height = r.R(12.f, 17.f);
				BuildHouse(blocks[blockOf(ToPolar(front.x, front.z).theta)], Frame::Facing(front, fx, fz), hp, seed * 31u);
				++w.houses;
				t += width;
			}
		};
		line(kPiazzaX0, kPiazzaZ0, kPiazzaX1, kPiazzaZ0, 0.f, 1.f);              // back
		line(kPiazzaX0, kPiazzaZ1 - 1.f, kPiazzaX0, kPiazzaZ0 + 0.2f, 1.f, 0.f); // west
		line(kPiazzaX1, kPiazzaZ0 + 0.2f, kPiazzaX1, kPiazzaZ1 - 1.f, -1.f, 0.f); // east
	}
	// A bell tower above the piazza.
	{
		const V3 p{-22.f, TerrainHeight(-22.f, -48.f), -48.f};
		Builder b{blocks[blockOf(ToPolar(p.x, p.z).theta)], Frame::Facing(p, 0.1f, 1.f)};
		b.Box({-2.2f, -6.f, -2.2f}, {2.2f, 24.f, 2.2f}, C_CREAM, M_PLASTER);
		b.Box({-2.4f, 18.f, -2.4f}, {2.4f, 18.3f, 2.4f}, C_TRIM_WHITE, M_PLAIN);
		for (int s = 0; s < 4; ++s)
		{
			const Frame face = Frame::Facing(p, std::sin((float)s * kPi * 0.5f + 0.1f), std::cos((float)s * kPi * 0.5f + 0.1f));
			Builder fb{b.m, face};
			fb.Box({-0.7f, 19.2f, 2.15f}, {0.7f, 22.2f, 2.25f}, C_GLASS, M_GLASS);
			fb.Box({-0.5f, 9.f, 2.15f}, {0.5f, 10.4f, 2.25f}, C_GLASS, M_GLASS);
		}
		b.Box({-2.5f, 24.f, -2.5f}, {2.5f, 24.4f, 2.5f}, C_TRIM_WHITE, M_PLAIN);
		const V3 apex{0.f, 28.f, 0.f};
		const V3 corners[4] = {{-2.4f, 24.4f, -2.4f}, {2.4f, 24.4f, -2.4f}, {2.4f, 24.4f, 2.4f}, {-2.4f, 24.4f, 2.4f}};
		for (int k = 0; k < 4; ++k)
		{
			const V3 tri[3] = {corners[k], corners[(k + 1) % 4], apex};
			const V3 mid = (corners[k] + corners[(k + 1) % 4]) * 0.5f;
			b.Poly(tri, 3, {mid.x, 1.f, mid.z}, C_ROOF_TERRA, M_ROOF);
		}
	}
}

void BuildHarbour(MeshData& m)
{
	Builder b{m, Frame{}};
	// Piazza and quay (cobbles on top, stone walls into the water).
	b.Box({kPiazzaX0, -4.f, kPiazzaZ0 - 3.f}, {kPiazzaX1, kPiazzaY, kPiazzaZ1}, C_PAVING, M_STONE, M_PAVING);
	// Pier.
	b.Box({6.f, -4.f, kPiazzaZ1 - 0.1f}, {10.f, kPiazzaY - 0.05f, 4.f}, C_PAVING, M_STONE, M_PAVING);
	b.Box({5.8f, kPiazzaY - 0.1f, 3.8f}, {10.2f, kPiazzaY + 0.5f, 4.2f}, C_STONE, M_STONE);
	// Bollards along the quay and the pier.
	for (float x : {-12.f, -6.f, 0.f})
		b.Prism({x, kPiazzaY, kPiazzaZ1 - 0.5f}, 0.18f, 0.55f, 8, C_IRON, M_PLAIN);
	for (float z : {-14.f, -7.f, 0.f}) b.Prism({9.5f, kPiazzaY - 0.05f, z}, 0.18f, 0.55f, 8, C_IRON, M_PLAIN);
	// Steps down to the water at the end of the quay.
	for (int i = 0; i < 6; ++i)
		b.Box({-15.5f + (float)i * 0.4f, -2.f, kPiazzaZ1 - 0.1f}, {-15.1f + (float)i * 0.4f, kPiazzaY - (float)i * 0.32f, kPiazzaZ1 + 1.2f}, C_STONE, M_STONE, M_PAVING);
	// Fountain.
	const V3 f{0.f, kPiazzaY, -27.f};
	for (int k = 0; k < 8; ++k)
	{
		const float a0 = (float)k / 8.f * 2.f * kPi, a1 = (float)(k + 1) / 8.f * 2.f * kPi;
		const V3 p0{f.x + std::cos(a0) * 2.4f, f.y, f.z + std::sin(a0) * 2.4f}, p1{f.x + std::cos(a1) * 2.4f, f.y, f.z + std::sin(a1) * 2.4f};
		const V3 q0{f.x + std::cos(a0) * 2.0f, f.y, f.z + std::sin(a0) * 2.0f}, q1{f.x + std::cos(a1) * 2.0f, f.y, f.z + std::sin(a1) * 2.0f};
		const V3 up{0.f, 0.6f, 0.f};
		const float am = (a0 + a1) * 0.5f;
		b.Quad(p0, p1, p1 + up, p0 + up, {std::cos(am), 0.f, std::sin(am)}, C_STONE, M_STONE);
		b.Quad(q0, q1, q1 + up, q0 + up, {-std::cos(am), 0.f, -std::sin(am)}, C_STONE, M_STONE);
		b.Quad(p0 + up, p1 + up, q1 + up, q0 + up, {0.f, 1.f, 0.f}, C_TRIM_CREAM, M_PLAIN);
	}
	b.Prism(f, 2.05f, 0.45f, 8, C_BOAT_SKY, M_GLASS); // water in the basin
	b.Prism(f, 0.22f, 1.7f, 8, C_TRIM_CREAM, M_PLAIN);
	b.Prism(f + V3{0.f, 1.3f, 0.f}, 0.75f, 0.12f, 8, C_TRIM_CREAM, M_PLAIN);
	b.Prism(f + V3{0.f, 1.42f, 0.f}, 0.65f, 0.05f, 8, C_BOAT_SKY, M_GLASS);
	b.Prism(f + V3{0.f, 1.7f, 0.f}, 0.12f, 0.6f, 6, C_TRIM_CREAM, M_PLAIN);
	b.Prism(f + V3{0.f, 2.3f, 0.f}, 0.2f, 0.2f, 6, C_TRIM_CREAM, M_PLAIN);
	// Cafe tables with parasols in the piazza.
	Rng r(77);
	for (int i = 0; i < 4; ++i)
	{
		const V3 t{-11.f + (float)i * 3.2f, kPiazzaY, -31.5f + (float)(i % 2) * 1.2f};
		b.Prism(t, 0.05f, 0.75f, 5, C_IRON, M_PLAIN, false);
		b.Prism(t + V3{0.f, 0.75f, 0.f}, 0.45f, 0.04f, 8, C_TRIM_WHITE, M_PLAIN);
		for (float s : {-1.f, 1.f}) b.BoxC(t + V3{s * 0.8f, 0.25f, 0.f}, {0.2f, 0.25f, 0.2f}, C_WOOD, M_WOOD);
		AddUmbrella(m, t, kAwnings[r.I(4)], 0.f);
	}
}

// Stone quays along the water front, in front of the first row of houses.
void BuildWaterfront(MeshData& m)
{
	const float step = 1.6f * kPi / 180.f;
	for (float th = -66.f * kPi / 180.f; th < 66.f * kPi / 180.f; th += step)
	{
		const float tc = th + step * 0.5f, deg = tc * 180.f / kPi;
		if (BeachMask(deg) > 0.05f) continue;
		const V3 a = FromPolar(th, -0.6f), b = FromPolar(th + step, -0.6f);
		const V3 c = FromPolar(th + step, 7.5f), d = FromPolar(th, 7.5f);
		const V3 mid = FromPolar(tc, 3.f);
		if (InPiazza(mid.x, mid.z, 1.5f)) continue;
		const float top = TerrainHeight(FromPolar(tc, 6.f).x, FromPolar(tc, 6.f).z) - 0.06f;
		Builder bl{m, Frame{}};
		const V3 up{0.f, top, 0.f}, down{0.f, -3.f, 0.f};
		const V3 out = mid - V3{kCoveX, 0.f, kCoveZ};
		bl.Quad(a + up, b + up, c + up, d + up, {0, 1, 0}, C_PAVING, M_PAVING);
		bl.Quad(a + down, b + down, b + up, a + up, -out, C_STONE, M_STONE);
		bl.Quad(a + down, d + down, d + up, a + up, a - b, C_STONE, M_STONE);
		bl.Quad(b + down, c + down, c + up, b + up, b - a, C_STONE, M_STONE);
	}
}

void BuildRocks(World& w, MeshData& m)
{
	Rng r(4242);
	auto place = [&](float theta, float d, float size)
	{
		const V3 p = FromPolar(theta, d);
		if (InPiazza(p.x, p.z, 3.f)) return;
		if (p.x > 4.f && p.x < 12.f && p.z > -22.f && p.z < 6.f) return; // pier
		const float ground = TerrainHeight(p.x, p.z);
		const V3 radii{size * r.R(0.9f, 1.4f), size * r.R(0.55f, 0.8f), size * r.R(0.8f, 1.2f)};
		const int slot = r.P(0.6f) ? C_ROCK : (r.P(0.5f) ? C_ROCK_WARM : C_ROCK_DARK);
		AddRock(m, {p.x, std::max(ground, -1.5f) + radii.y * 0.15f, p.z}, radii, r.R(0.f, 6.28f), (uint32_t)w.rocks * 7u + 3u, slot);
		++w.rocks;
	};
	// Along the shore, except the piazza and the beach.
	for (float deg = -128.f; deg <= 128.f; deg += r.R(1.2f, 2.6f))
	{
		if (BeachMask(deg) > 0.1f) continue;
		const float th = deg * kPi / 180.f;
		const float side = Smooth(60.f, 100.f, std::abs(deg));
		place(th, r.R(-2.5f, 1.5f), r.R(1.6f, 3.4f) * (1.f + side * 0.6f));
		if (r.P(0.6f)) place(th + r.R(-0.01f, 0.01f), r.R(-5.f, -2.f), r.R(0.9f, 2.4f));
		if (r.P(0.5f)) place(th, r.R(1.f, 4.f), r.R(1.2f, 3.f) * (1.f + side));
	}
	// A few boulders in the water.
	for (int i = 0; i < 14; ++i) place(r.R(-1.9f, 1.9f), r.R(-9.f, -4.f), r.R(0.7f, 1.8f));
	// Rocky headlands.
	for (int i = 0; i < 60; ++i)
	{
		const float deg = (r.P(0.5f) ? 1.f : -1.f) * r.R(85.f, 135.f);
		place(deg * kPi / 180.f, r.R(-4.f, 14.f), r.R(2.f, 5.5f));
	}
}

void BuildBoats(World& w, HRL_id material)
{
	struct Spot { float x, z, yawDeg; bool beached; };
	const Spot spots[] = {{3.5f, -12.f, 90.f, false}, {12.5f, -10.f, 80.f, false}, {3.2f, -4.f, 95.f, false}, {13.f, -1.f, 100.f, false},
		{-6.f, -16.f, 10.f, false}, {-11.f, -15.5f, -5.f, false}, {0.5f, -15.f, 170.f, false}, {-2.f, 6.f, 60.f, false},
		{18.f, 12.f, 140.f, false}, {-16.f, 10.f, 30.f, false}, {-30.f, 30.f, 120.f, false}};
	const int hulls[] = {C_BOAT_WHITE, C_BOAT_BLUE, C_BOAT_YELLOW, C_BOAT_RED, C_BOAT_GREEN, C_BOAT_SKY, C_BOAT_WHITE};
	uint32_t seed = 9;
	auto add = [&](float x, float y, float z, float yawDeg, bool floating)
	{
		Rng r(seed);
		MeshData boat = MakeBoat(r.R(4.f, 5.6f), r.R(1.5f, 1.8f), 0.55f, hulls[r.I(7)], seed++);
		const float a = yawDeg * kPi / 180.f, c = std::cos(a), s = std::sin(a);
		for (HRL_Vertex3D& v : boat.vertices)
		{
			auto rot = [&](float* p) { const float px = p[0], pz = p[2]; p[0] = px * c - pz * s; p[2] = px * s + pz * c; };
			rot(v.position); rot(v.normal); rot(v.tangent); rot(v.bitangent);
		}
		const HRL_id mesh = HRL_CreateMesh3D(w.scene, boat.vertices.data(), boat.vertices.size(), boat.indices.data(), boat.indices.size());
		HRL_SetMeshMaterial(mesh, material);
		HRL_SetMeshLocation(mesh, x, y, z);
		if (floating) w.boats.push_back({mesh, x, y, z, r.R(0.f, 6.28f), r.R(0.6f, 1.f)});
		else HRL_SetMeshRotation(mesh, r.R(-4.f, 4.f), 0.f, r.R(6.f, 12.f));
	};
	for (const Spot& s : spots) add(s.x, -0.12f, s.z, s.yawDeg, true);
	// Pulled up on the beach.
	for (int i = 0; i < 4; ++i)
	{
		const float th = (27.f + (float)i * 4.f) * kPi / 180.f;
		const V3 p = FromPolar(th, 4.f + (float)(i % 2) * 2.f);
		add(p.x, TerrainHeight(p.x, p.z) + 0.25f, p.z, -th * 180.f / kPi + 90.f + (float)i * 9.f, false);
	}
}

void BuildBeach(MeshData& m)
{
	const int colors[] = {C_AWN_RED, C_AWN_BLUE, C_AWN_YELLOW, C_AWN_GREEN, C_AWN_RED, C_BOAT_SKY};
	Rng r(31);
	for (int i = 0; i < 9; ++i)
	{
		const float th = r.R(24.f, 42.f) * kPi / 180.f;
		const V3 p = FromPolar(th, r.R(7.f, 16.f));
		AddUmbrella(m, {p.x, TerrainHeight(p.x, p.z) - 0.1f, p.z}, colors[i % 6], r.R(-0.2f, 0.2f));
		Builder b{m, Frame::Facing({p.x, TerrainHeight(p.x, p.z), p.z}, r.R(-1.f, 1.f), 1.f)};
		b.Box({-0.45f, 0.01f, 0.4f}, {0.45f, 0.03f, 2.2f}, colors[(i + 2) % 6], M_STRIPES); // towel
	}
}

void BuildTrees(World& w, HRL_id leafLight, HRL_id leafMid, HRL_id leafDark, HRL_id leafCypress, HRL_id bark)
{
	struct Kind { HRL_id foliage; std::vector<HRL_FoliageInstance> instances; };
	Kind kinds[5];
	auto makeKind = [&](int i, const MeshData& trunk, HRL_id trunkMat, const MeshData& canopy, HRL_id canopyMat, float wind)
	{
		kinds[i].foliage = HRL_CreateFoliage(w.scene);
		HRL_AddFoliageMesh(kinds[i].foliage, trunk.vertices.data(), trunk.vertices.size(), trunk.indices.data(), trunk.indices.size(), trunkMat);
		HRL_AddFoliageMesh(kinds[i].foliage, canopy.vertices.data(), canopy.vertices.size(), canopy.indices.data(), canopy.indices.size(), canopyMat);
		HRL_SetFoliageDrawDistance(kinds[i].foliage, 1100.f);
		HRL_SetFoliageLODDistance(kinds[i].foliage, 60.f);
		HRL_SetFoliageImpostorDistance(kinds[i].foliage, 220.f);
		HRL_SetFoliageWindResponse(kinds[i].foliage, wind);
	};
	makeKind(0, MakeTrunk(0.3f, 0.18f, 4.5f, 0.f, 7), bark, MakeRoundCanopy(1u, 1.f), leafLight, 0.25f);
	makeKind(1, MakeTrunk(0.3f, 0.18f, 4.5f, 0.f, 7), bark, MakeRoundCanopy(2u, 1.f), leafMid, 0.25f);
	makeKind(2, MakeTrunk(0.3f, 0.18f, 4.5f, 0.f, 7), bark, MakeRoundCanopy(3u, 1.1f), leafDark, 0.25f);
	makeKind(3, MakeTrunk(0.22f, 0.12f, 2.f, 0.f, 6), bark, MakeCypress(4u), leafCypress, 0.15f);
	makeKind(4, MakeTrunk(0.32f, 0.2f, 8.f, 0.6f, 7), bark, MakePineCanopy(5u), leafDark, 0.2f);

	const float half = kLandSize * 0.5f - 4.f;
	for (float z = kLandCenterZ - half; z < kLandCenterZ + half; z += 3.2f)
		for (float x = -half; x < half; x += 3.2f)
		{
			const float jx = x + (Hash2((int)(x * 7.f), (int)(z * 3.f)) - 0.5f) * 3.f;
			const float jz = z + (Hash2((int)(x * 5.f), (int)(z * 11.f)) - 0.5f) * 3.f;
			const float h = TerrainHeight(jx, jz);
			if (h < 2.5f) continue;
			const Polar p = ToPolar(jx, jz);
			const float deg = p.theta * 180.f / kPi;
			// Not in the village (a few trees in its upper part and along its edges).
			if (std::abs(deg) < VillageEdgeDeg(p.d) + 1.f && p.d > -2.f && p.d < 88.f && Hash2((int)jx, (int)jz * 3) > 0.02f) continue;
			if (BeachMask(deg) > 0.1f && p.d < 28.f) continue;
			const V3 n = TerrainNormal(jx, jz);
			if (n.y < 0.72f) continue;
			const float forest = ForestDensity(jx, jz);
			const float keep = 0.04f + 0.9f * forest;
			const float roll = Hash2((int)(jx * 13.f), (int)(jz * 17.f));
			if (roll > keep) continue;
			const float pick = Hash2((int)(jx * 3.f) + 11, (int)(jz * 5.f));
			int kind = pick < 0.35f ? 0 : (pick < 0.65f ? 1 : (pick < 0.85f ? 2 : 3));
			if (forest < 0.3f && pick > 0.5f) kind = pick > 0.8f ? 4 : 3; // pines and cypresses on the open terraces
			HRL_FoliageInstance inst{};
			inst.position[0] = jx;
			inst.position[1] = h - 0.2f;
			inst.position[2] = jz;
			inst.rotation[1] = roll * 360.f * 7.f;
			inst.scale = 0.75f + 0.55f * Hash2((int)jz, (int)jx);
			kinds[kind].instances.push_back(inst);
		}
	// Cypresses and pines lining the top of the village and the road.
	for (int i = 0; i < 40; ++i)
	{
		const float th = (-60.f + (float)i * 3.f) * kPi / 180.f;
		const V3 p = FromPolar(th, 94.f + Hash2(i, 3) * 4.f);
		HRL_FoliageInstance inst{};
		inst.position[0] = p.x;
		inst.position[1] = TerrainHeight(p.x, p.z) - 0.2f;
		inst.position[2] = p.z;
		inst.rotation[1] = Hash2(i, 5) * 360.f;
		inst.scale = 0.9f + 0.3f * Hash2(i, 9);
		kinds[i % 3 == 0 ? 4 : 3].instances.push_back(inst);
	}
	for (Kind& k : kinds)
	{
		w.trees += HRL_AddFoliageInstances(k.foliage, k.instances.data(), k.instances.size());
	}
}

// Cartoon cumulus: clusters of soft blobs, flat underneath, far in the sky.
MeshData MakeClouds()
{
	MeshData m;
	Rng r(2024);
	for (int c = 0; c < 26; ++c)
	{
		// Mostly over the sea (+Z) and above the hills, around the cove.
		const float a = (c < 16 ? kPi * 0.5f : -kPi * 0.5f) + r.R(-1.2f, 1.2f);
		const float dist = r.R(1300.f, 2400.f);
		// Higher above the hills, so they show over the ridges.
		const V3 center{std::cos(a) * dist, c < 16 ? r.R(260.f, 520.f) : r.R(560.f, 820.f), kCoveZ + std::sin(a) * dist};
		const float size = r.R(70.f, 160.f);
		const int blobs = 5 + r.I(6);
		for (int b = 0; b < blobs; ++b)
		{
			const float t = blobs > 1 ? (float)b / (float)(blobs - 1) - 0.5f : 0.f;
			const float bump = 1.f - 2.f * std::abs(t);
			const V3 offset{t * size * 2.2f + r.R(-0.15f, 0.15f) * size, size * (0.15f + 0.45f * bump) * r.R(0.6f, 1.1f), r.R(-0.3f, 0.3f) * size};
			const float rad = size * (0.35f + 0.4f * bump) * r.R(0.8f, 1.15f);
			// Turned towards the cove (the clusters are long across the view).
			const float tx = -std::sin(a), tz = std::cos(a);
			const V3 p{center.x + offset.x * tx + offset.z * tz, center.y + offset.y, center.z + offset.x * tz - offset.z * tx};
			AddBlob(m, p, {rad, rad * 0.75f, rad}, (uint32_t)(c * 31 + b), 0.35f);
		}
	}
	return m;
}

// Fine water near the village (vertex waves), coarse up to the horizon.
MeshData MakeWater()
{
	MeshData m;
	const int n = 160;
	const float x0 = -240.f, z0 = -60.f, size = 480.f;
	for (int j = 0; j <= n; ++j)
		for (int i = 0; i <= n; ++i)
		{
			const float x = x0 + size * (float)i / n, z = z0 + size * (float)j / n;
			m.vertices.push_back(MakeVertex({x, 0.f, z}, {0.f, 1.f, 0.f}, 0.f, 0.f, {1.f, 0.f, 0.f}));
		}
	for (int j = 0; j < n; ++j)
		for (int i = 0; i < n; ++i)
		{
			const HRL_uint a = (HRL_uint)(j * (n + 1) + i), b = a + 1, c = a + n + 1, d = c + 1;
			m.indices.insert(m.indices.end(), {a, c, b, b, c, d});
		}
	// Ring of four large quads around it (to the horizon).
	Builder bld{m, Frame{}};
	const float far = 6000.f, x1 = x0 + size, z1 = z0 + size;
	bld.Quad({-far, 0.f, -far}, {far, 0.f, -far}, {far, 0.f, z0}, {-far, 0.f, z0}, {0, 1, 0}, 0, 0);
	bld.Quad({-far, 0.f, z1}, {far, 0.f, z1}, {far, 0.f, far}, {-far, 0.f, far}, {0, 1, 0}, 0, 0);
	bld.Quad({-far, 0.f, z0}, {x0, 0.f, z0}, {x0, 0.f, z1}, {-far, 0.f, z1}, {0, 1, 0}, 0, 0);
	bld.Quad({x1, 0.f, z0}, {far, 0.f, z0}, {far, 0.f, z1}, {x1, 0.f, z1}, {0, 1, 0}, 0, 0);
	return m;
}

void BuildWorld(World& w, const Options& opt)
{
	w.scene = HRL_CreateScene(HRL_TRUE);
	w.camera = HRL_CreateCamera(w.scene, HRL_PERSPECTIVE);
	HRL_SetCameraPerspectiveFov(w.camera, 55.f);
	HRL_SetCameraNearPlane(w.camera, 0.1f);
	HRL_SetCameraFarPlane(w.camera, 5000.f);
	const HRL_id viewport = HRL_CreateViewport(w.scene, w.camera, 0.f, 0.f, 1.f, 1.f);

	// Warm, saturated grading.
	w.post = HRL_CreateMaterial(HRL_DEFAULT_POST_PROCESS_SHADER);
	HRL_MaterialSetFloat(w.post, "exposure", 0.15f);
	HRL_MaterialSetFloat(w.post, "bloomStrength", 0.9f);
	HRL_MaterialSetFloat(w.post, "saturation", 1.22f);
	HRL_MaterialSetFloat(w.post, "contrast", 1.06f);
	HRL_MaterialSetVec3(w.post, "tintColor", 1.03f, 1.0f, 0.96f);
	HRL_MaterialSetFloat(w.post, "vignetteStrength", 0.22f);
	HRL_MaterialSetFloat(w.post, "vignetteRadius", 0.8f);
	HRL_MaterialSetFloat(w.post, "vignetteSoftness", 0.45f);
	HRL_CreatePostProcess(viewport, w.post, 0);

	// Sky and sun of a summer afternoon.
	HRL_SetSkySphereEnabled(w.scene, HRL_TRUE);
	// The lower half is a sea blue: it is what the waves reflect at grazing angles.
	HRL_SetSkySphereColors(w.scene, 0.03f, 0.17f, 0.75f, 0.30f, 0.55f, 0.95f, 0.06f, 0.22f, 0.42f);
	HRL_SetEnvironmentMappingEnabled(w.scene, HRL_TRUE);
	HRL_SetFogEnabled(w.scene, HRL_TRUE);
	HRL_SetFogMode(w.scene, HRL_FOG_EXPONENTIAL);
	HRL_SetFogColor(w.scene, 0.52f, 0.70f, 0.95f);
	HRL_SetFogDensity(w.scene, 0.0004f);
	const HRL_id sun = HRL_CreateLight(w.scene, HRL_DIRECTIONAL_LIGHT);
	HRL_SetLightRotation(sun, -30.f, -150.f, 0.f);
	HRL_SetLightColor(sun, 1.f, 0.84f, 0.62f);
	HRL_SetLightIntensity(sun, 5.2f);
	HRL_SetLightCastShadows(sun, HRL_TRUE);
	HRL_SetLightShadowResolution(sun, 4096);
	HRL_Vulkan_SetShadowDistance(260.f);
	HRL_SetAmbientOcclusionEnabled(w.scene, HRL_TRUE);
	HRL_SetAmbientOcclusionStrength(w.scene, 0.9f);
	HRL_SetAmbientOcclusionRadius(w.scene, 0.8f);
	if (opt.volumetricClouds)
	{
		HRL_SetVolumetricCloudEnabled(w.scene, HRL_TRUE);
		HRL_SetVolumetricCloudCoverage(w.scene, 0.58f);
		HRL_SetVolumetricCloudDensity(w.scene, 0.9f);
		HRL_SetVolumetricCloudHeight(w.scene, 450.f, 900.f);
		HRL_SetVolumetricCloudColor(w.scene, 1.f, 1.f, 1.f);
		HRL_SetVolumetricCloudLightColor(w.scene, 1.f, 0.92f, 0.82f);
		HRL_SetVolumetricCloudWind(w.scene, 1.f, 0.3f, 4.f);
	}
	if (opt.gi && HRL_IsGlobalIlluminationMethodSupported(HRL_GI_DDGI))
	{
		HRL_SetGlobalIlluminationMethod(w.scene, HRL_GI_DDGI);
		HRL_SetGlobalIlluminationEnabled(w.scene, HRL_TRUE);
		HRL_SetGlobalIlluminationIntensity(w.scene, 1.2f);
	}

	// ---- Materials ----
	const HRL_id palette = MakePaletteTexture();
	HRL_id villageShader = CompileShader(nullptr, MakeVillageShaderSource());
	HRL_id waterShader = CompileShader(kWaterVertex, kWaterSurface);
	if (villageShader == HRL_INVALID_ID || waterShader == HRL_INVALID_ID)
		std::printf("custom shaders not available: flat colours\n");
	HRL_id village = MakeMaterial(villageShader != HRL_INVALID_ID ? villageShader : HRL_MESH_3D_SHADER, palette, 0.85f);
	HRL_id boatMat = MakeMaterial(villageShader != HRL_INVALID_ID ? villageShader : HRL_MESH_3D_SHADER, palette, 0.6f);
	HRL_MaterialSetBool(boatMat, HRL_MATERIAL_PARAM_TWO_SIDED, HRL_TRUE);
	HRL_id water;
	if (waterShader != HRL_INVALID_ID)
	{
		water = HRL_CreateMaterial(waterShader);
		HRL_MaterialSetTexture(water, "Depth", MakeDepthTexture());
		HRL_MaterialSetVec4(water, "DepthRect", -kLandSize * 0.5f, kLandCenterZ - kLandSize * 0.5f, kLandSize, kLandSize);
	}
	else
	{
		water = MakeMaterial(HRL_MESH_3D_SHADER, HRL_INVALID_ID, 0.05f);
		HRL_MaterialSetVec3(water, "TintColor", 0.05f, 0.55f, 0.6f);
		HRL_MaterialSetInt(water, "OpacityUseValue", 1);
		HRL_MaterialSetFloat(water, "OpacityValue", 0.7f);
	}
	HRL_MaterialSetBool(water, HRL_MATERIAL_PARAM_TRANSLUCENT, HRL_TRUE);

	// ---- Landscape ----
	std::vector<float> heights((size_t)kLandSamples * kLandSamples);
	for (int j = 0; j < kLandSamples; ++j)
		for (int i = 0; i < kLandSamples; ++i)
		{
			const float x = ((float)i / (float)(kLandSamples - 1) - 0.5f) * kLandSize;
			const float z = ((float)j / (float)(kLandSamples - 1) - 0.5f) * kLandSize + kLandCenterZ;
			heights[(size_t)j * kLandSamples + i] = TerrainHeight(x, z);
		}
	w.land = HRL_CreateLandscapeFromHeights(w.scene, heights.data(), (HRL_uint)kLandSamples, (HRL_uint)kLandSamples);
	HRL_SetLandscapeSize(w.land, kLandSize, kLandSize);
	HRL_SetLandscapePosition(w.land, 0.f, 0.f, kLandCenterZ);
	HRL_SetLandscapeUVScale(w.land, 1.f, 1.f);
	HRL_SetLandscapeMaterial(w.land, MakeMaterial(HRL_MESH_3D_SHADER, MakeGroundTexture(), 0.92f));

	// ---- Water ----
	AddMeshTo(w, MakeWater(), water);

	// ---- Clouds ----
	if (!opt.volumetricClouds)
	{
		const HRL_id cloud = MakeMaterial(HRL_MESH_3D_SHADER, HRL_INVALID_ID, 1.f);
		HRL_MaterialSetVec3(cloud, "TintColor", 1.f, 1.f, 1.f);
		HRL_MaterialSetEmissiveColor(cloud, 0.78f, 0.84f, 0.95f, 1.6f);
		AddMeshTo(w, MakeClouds(), cloud);
	}

	// ---- Village, harbour, rocks, beach ----
	MeshData blocks[8];
	BuildVillage(w, blocks);
	for (const MeshData& b : blocks) AddMeshTo(w, b, village);
	MeshData harbour;
	BuildHarbour(harbour);
	BuildWaterfront(harbour);
	BuildBeach(harbour);
	AddMeshTo(w, harbour, village);
	MeshData rocks[2];
	BuildRocks(w, rocks[0]);
	// Two meshes: west and east of the cove.
	{
		MeshData west, east;
		// Split by the X of each triangle's first vertex.
		const MeshData& all = rocks[0];
		for (size_t k = 0; k < all.indices.size(); k += 3)
		{
			MeshData& dst = all.vertices[all.indices[k]].position[0] < 0.f ? west : east;
			const HRL_uint base = (HRL_uint)dst.vertices.size();
			for (int j = 0; j < 3; ++j) dst.vertices.push_back(all.vertices[all.indices[k + j]]);
			dst.indices.insert(dst.indices.end(), {base, base + 1, base + 2});
		}
		AddMeshTo(w, west, village);
		AddMeshTo(w, east, village);
	}
	BuildBoats(w, boatMat);

	// ---- Trees ----
	const HRL_id bark = MakeMaterial(HRL_MESH_3D_SHADER, MakeBarkTexture(), 0.9f);
	const HRL_id leafLight = MakeMaterial(HRL_MESH_3D_SHADER, MakeCanopyTexture(0.40f, 0.62f, 0.14f, 1.f), 0.8f);
	const HRL_id leafMid = MakeMaterial(HRL_MESH_3D_SHADER, MakeCanopyTexture(0.24f, 0.50f, 0.12f, 0.6f), 0.8f);
	const HRL_id leafDark = MakeMaterial(HRL_MESH_3D_SHADER, MakeCanopyTexture(0.14f, 0.36f, 0.10f, 0.3f), 0.8f);
	const HRL_id leafCypress = MakeMaterial(HRL_MESH_3D_SHADER, MakeCanopyTexture(0.10f, 0.26f, 0.09f, 0.f), 0.8f);
	BuildTrees(w, leafLight, leafMid, leafDark, leafCypress, bark);
	HRL_SetWind(w.scene, 1.f, 0.3f, 0.35f, 0.5f);

	HRL_Vulkan_SetRayTracedShadows(opt.rayTracedShadows ? HRL_TRUE : HRL_FALSE);
	std::printf("houses %zu, rocks %zu, boats %zu, trees %zu\n", w.houses, w.rocks, w.boats.size(), w.trees);
	w.view = Viewpoint(opt.view);
}

void UpdateWorld(World& w, float time)
{
	HRL_SetCameraLocation(w.camera, w.view.x, w.view.y, w.view.z);
	HRL_SetCameraRotation(w.camera, w.view.pitch, w.view.yaw, 0.f);
	// The boats bob and roll on the waves.
	for (const Boat& b : w.boats)
	{
		const float t = time * 1.3f + b.phase;
		HRL_SetMeshLocation(b.mesh, b.x, b.y + 0.05f * std::sin(t) * b.amplitude, b.z);
		HRL_SetMeshRotation(b.mesh, 2.0f * std::sin(t * 0.8f + 1.f) * b.amplitude, 0.f, 3.5f * std::sin(t * 0.9f) * b.amplitude);
	}
}

