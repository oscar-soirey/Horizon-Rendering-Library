// Patterns of the buildings, rocks and boats, drawn from the world position.
// U: palette slot, V: mode (see enum Mode).
const char* kVillageSurfaceBody = R"(
float vHash(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
float vNoise(vec2 p)
{
	vec2 i = floor(p), f = fract(p);
	f = f * f * (3.0 - 2.0 * f);
	return mix(mix(vHash(i), vHash(i + vec2(1.0, 0.0)), f.x), mix(vHash(i + vec2(0.0, 1.0)), vHash(i + vec2(1.0, 1.0)), f.x), f.y);
}
float vFbm(vec2 p)
{
	float s = 0.0, a = 0.5;
	for (int k = 0; k < 4; ++k) { s += a * vNoise(p); p = p * 2.03 + vec2(17.0, -9.0); a *= 0.5; }
	return s;
}
// x: distance between the two nearest cells (edges), yz: id of the nearest cell.
vec3 vVoronoi(vec2 x)
{
	vec2 n = floor(x), f = fract(x);
	float d1 = 8.0, d2 = 8.0;
	vec2 id = vec2(0.0);
	for (int j = -1; j <= 1; ++j)
		for (int i = -1; i <= 1; ++i)
		{
			vec2 g = vec2(float(i), float(j));
			vec2 o = vec2(vHash(n + g), vHash(n + g + 19.7));
			vec2 r = g + o - f;
			float d = dot(r, r);
			if (d < d1) { d2 = d1; d1 = d; id = n + g; }
			else if (d < d2) d2 = d;
		}
	return vec3(sqrt(d2) - sqrt(d1), id);
}
// Coordinates on the surface: along the wall and up, or x/z on the ground.
vec2 vWall(vec3 p, vec3 n)
{
	if (abs(n.y) > 0.7) return p.xz;
	vec2 t = normalize(vec2(-n.z, n.x) + vec2(1e-5));
	return vec2(dot(p.xz, t), p.y);
}
vec3 vStoneWall(vec3 c, vec2 w)
{
	vec2 q = w * vec2(1.0 / 0.55, 1.0 / 0.32);
	float row = floor(q.y);
	q.x += vHash(vec2(row, 4.1)) * 3.0;
	vec2 f = fract(q), id = floor(q);
	float e = min(min(f.x, 1.0 - f.x) * 0.55, min(f.y, 1.0 - f.y) * 0.32);
	c *= (0.78 + 0.34 * vHash(id)) * (0.92 + 0.12 * vNoise(w * 9.0));
	return mix(c * 0.55, c, smoothstep(0.01, 0.035, e));
}

void Surface(HRL_SurfaceInput i, inout HRL_Surface s)
{
	int slot = clamp(int(i.uv.x * float(PALETTE_SLOTS)), 0, PALETTE_COUNT - 1);
	int mode = int(floor(i.uv.y));
	vec3 c = PALETTE[slot];
	vec3 p = i.worldPosition, n = i.normal;
	vec2 w = vWall(p, n);
	float rough = 0.85, spec = 0.5;
	if (mode == 0)
	{
		// Plaster: soft blotches, rain streaks, a few patches of bare stones.
		c *= 0.86 + 0.26 * vFbm(w * 0.35) + 0.06 * vNoise(w * 7.0);
		c *= 1.0 - 0.12 * smoothstep(0.55, 0.95, vNoise(vec2(w.x * 2.5, w.y * 0.12)));
		float bare = vFbm(w * 0.45 + 31.0);
		if (abs(n.y) < 0.5 && bare > 0.66)
		{
			vec3 v = vVoronoi(w * vec2(3.0, 4.5));
			vec3 st = vec3(0.42, 0.36, 0.31) * (0.75 + 0.4 * vHash(v.yz));
			st *= mix(0.55, 1.0, smoothstep(0.02, 0.12, v.x));
			c = mix(c, st, smoothstep(0.66, 0.7, bare));
		}
	}
	else if (mode == 1)
	{
		// Barrel tiles in rows down the slope, a little moss.
		if (n.y > 0.2 && n.y < 0.985)
		{
			vec2 d = normalize(n.xz);
			float row = dot(p.xz, d) / max(n.y, 0.3) * 3.3;
			float ri = floor(row), rf = fract(row);
			float col = dot(p.xz, vec2(-d.y, d.x)) * 4.2 + 0.5 * mod(ri, 2.0);
			float ci = floor(col), cf = fract(col);
			float barrel = 0.68 + 0.32 * sin(cf * 3.14159);
			float gap = smoothstep(0.0, 0.08, cf) * smoothstep(1.0, 0.92, cf);
			float overlap = mix(0.5, 1.0, smoothstep(0.0, 0.28, rf));
			c *= barrel * overlap * (0.8 + 0.34 * vHash(vec2(ri, ci))) * mix(0.65, 1.0, gap);
			c = mix(c, c * vec3(0.72, 0.78, 0.62), smoothstep(0.5, 0.8, vFbm(p.xz * 0.25)) * 0.6);
			rough = 0.7;
		}
		else c *= 0.85;
	}
	else if (mode == 2)
	{
		// Rounded rock: wavy strata, lighter tops, wet and dark at the water line.
		float warp = vFbm(p.xz * 0.12 + vec2(p.y * 0.05)) * 4.0;
		float strata = 0.5 + 0.5 * sin(p.y * 2.6 + warp);
		float grain = vFbm(vec2(dot(p.xz, vec2(0.7071)), p.y) * 1.3);
		c *= 0.78 + 0.16 * smoothstep(0.3, 0.7, strata) + 0.2 * grain;
		c *= mix(1.0, 1.15, smoothstep(0.55, 0.95, n.y));
		float wet = 1.0 - smoothstep(0.05, 0.9, p.y);
		c = mix(c, c * vec3(0.5, 0.58, 0.48), wet * 0.75);
		rough = mix(0.8, 0.3, wet);
	}
	else if (mode == 3) { c = vStoneWall(c, w); rough = 0.9; }
	else if (mode == 4)
	{
		// Cobbles on top, stones on the sides.
		if (n.y > 0.7)
		{
			vec3 v = vVoronoi(p.xz / 0.38);
			c *= (0.80 + 0.30 * vHash(v.yz)) * (0.92 + 0.12 * vNoise(p.xz * 6.0));
			c = mix(c * 0.5, c, smoothstep(0.04, 0.16, v.x));
			rough = 0.8;
		}
		else c = vStoneWall(c, w);
	}
	else if (mode == 5) { c *= 0.95 + 0.08 * vNoise(w * 3.0); rough = 0.6; }
	else if (mode == 6)
	{
		vec2 d = length(n.xz) > 0.05 ? normalize(n.xz) : vec2(1.0, 0.0);
		if (fract(dot(p.xz, vec2(-d.y, d.x)) / 0.5) < 0.5) c = PALETTE[14];
		rough = 0.7;
	}
	else if (mode == 7)
	{
		float plank = floor(w.y * 6.0);
		c *= (0.82 + 0.25 * vHash(vec2(plank, 2.0))) * (0.9 + 0.15 * vNoise(vec2(w.x * 1.5, w.y * 40.0)));
		c *= mix(0.6, 1.0, smoothstep(0.0, 0.08, fract(w.y * 6.0)));
		rough = 0.7;
	}
	else if (mode == 8)
	{
		// Leaves and flowers.
		vec3 v = vVoronoi(w / 0.07);
		float h = vHash(v.yz);
		vec3 leaf = vec3(0.07, 0.22, 0.04) * (0.7 + 0.7 * vHash(v.yz + 3.0));
		vec3 flower = h < 0.3 ? vec3(0.85, 0.06, 0.10) : (h < 0.55 ? vec3(0.95, 0.30, 0.55) : (h < 0.7 ? vec3(0.95, 0.9, 0.85) : vec3(0.95, 0.6, 0.08)));
		c = vHash(v.yz + 7.0) > 0.55 ? flower : leaf;
		c *= mix(0.5, 1.0, smoothstep(0.0, 0.2, v.x));
		rough = 0.8;
	}
	else if (mode == 9) { c *= 0.72 + 0.28 * smoothstep(0.0, 0.5, fract(p.y * 13.0)); rough = 0.55; }
	else if (mode == 10)
	{
		c += vec3(0.02, 0.03, 0.05) * smoothstep(0.3, 1.0, vNoise(w * 0.8));
		rough = 0.12; spec = 1.0;
	}
	else if (mode == 11) { c *= 0.9 + 0.15 * vNoise(p.xz * 4.0); rough = 0.95; }
	s.baseColor = c;
	s.roughness = rough;
	s.metallic = 0.0;
	s.specular = spec;
}
)";

// Water: small moving waves, colour from the depth of the sea bed, foam along
// the shore, more opaque in deep water and at grazing angles.
const char* kWaterVertex = R"(
void Vertex(inout HRL_VertexData v)
{
	vec2 p = v.worldPosition.xz;
	float t = v.time;
	v.worldPosition.y += 0.05 * sin(dot(p, vec2(0.21, 0.13)) + t * 1.1) + 0.03 * sin(dot(p, vec2(-0.17, 0.29)) + t * 1.7);
}
)";
const char* kWaterSurface = R"(
uniform sampler2D Depth;
uniform vec4 DepthRect = vec4(-384.0, -424.0, 768.0, 768.0);
uniform vec3 Shallow = vec3(0.04, 0.62, 0.52);
uniform vec3 Middle = vec3(0.0, 0.26, 0.44);
uniform vec3 Deep = vec3(0.0, 0.06, 0.24);

float wHash(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
float wNoise(vec2 p)
{
	vec2 i = floor(p), f = fract(p);
	f = f * f * (3.0 - 2.0 * f);
	return mix(mix(wHash(i), wHash(i + vec2(1.0, 0.0)), f.x), mix(wHash(i + vec2(0.0, 1.0)), wHash(i + vec2(1.0, 1.0)), f.x), f.y);
}
float wWaves(vec2 p, float t)
{
	float h = 0.0;
	h += 0.050 * sin(dot(p, vec2(0.8, 0.5)) + t * 1.3);
	h += 0.035 * sin(dot(p, vec2(-0.6, 1.1)) + t * 1.7);
	h += 0.020 * sin(dot(p, vec2(1.7, -0.9)) + t * 2.3);
	h += 0.040 * wNoise(p * 1.2 + vec2(t * 0.4, -t * 0.3));
	h += 0.020 * wNoise(p * 3.1 - vec2(t * 0.6, t * 0.2));
	return h;
}

void Surface(HRL_SurfaceInput i, inout HRL_Surface s)
{
	vec2 p = i.worldPosition.xz;
	float t = i.time;
	float e = 0.08;
	float h0 = wWaves(p, t);
	vec3 n = normalize(vec3(-(wWaves(p + vec2(e, 0.0), t) - h0) / e, 1.0, -(wWaves(p + vec2(0.0, e), t) - h0) / e));
	vec2 uv = (p - DepthRect.xy) / DepthRect.zw;
	float depth = 1.0;
	if (uv.x > 0.0 && uv.x < 1.0 && uv.y > 0.0 && uv.y < 1.0) depth = textureLod(Depth, uv, 0.0).r;
	float dm = depth * 12.0;
	vec3 col = mix(Shallow, Middle, smoothstep(0.4, 3.5, dm));
	col = mix(col, Deep, smoothstep(3.5, 11.0, dm));
	// Caustic glints over the shallow sand.
	float caustic = pow(wNoise(p * 2.2 + vec2(t * 0.5, t * 0.3)) * wNoise(p * 2.9 - vec2(t * 0.4, -t * 0.2)), 2.0);
	col += vec3(0.25, 0.35, 0.3) * caustic * (1.0 - smoothstep(0.5, 4.0, dm));
	// Foam: a band along the shore that breathes with the waves.
	float fn = wNoise(p * 1.6 + vec2(t * 0.3, 0.0)) - 0.5;
	float band = dm + fn * 0.35 - 0.12 * sin(t * 1.4 + p.x * 0.15 + p.y * 0.1);
	float foam = smoothstep(0.35, 0.05, band) * smoothstep(0.2, 0.6, wNoise(p * 4.0 + vec2(0.0, t * 0.5)) + 0.35);
	float fresnel = pow(1.0 - clamp(dot(n, i.viewDirection), 0.0, 1.0), 4.0);
	float opacity = mix(0.45, 0.96, smoothstep(0.0, 7.0, dm));
	opacity = mix(opacity, 1.0, fresnel * 0.8);
	col = mix(col, vec3(0.95, 0.98, 1.0), foam);
	s.baseColor = col;
	s.normal = normalize(mix(n, vec3(0.0, 1.0, 0.0), foam));
	s.roughness = mix(0.05, 0.7, foam);
	s.metallic = 0.0;
	s.specular = 0.6;
	// Stylized: the sky reflected at grazing angles is toned down, so the sea stays a deep blue.
	s.ao = 1.0 - 0.5 * fresnel * (1.0 - foam);
	s.opacity = max(opacity, foam);
}
)";

std::string MakeVillageShaderSource()
{
	std::string src = "#define PALETTE_SLOTS " + std::to_string(kPaletteSlots) + "\n#define PALETTE_COUNT " + std::to_string(C_COUNT) +
		"\nconst vec3 PALETTE[" + std::to_string(C_COUNT) + "] = vec3[](";
	char buf[96];
	for (int i = 0; i < C_COUNT; ++i)
	{
		std::snprintf(buf, sizeof(buf), "%svec3(%.4f, %.4f, %.4f)", i ? ", " : "", SRGBToLinear(kPalette[i][0] / 255.f),
			SRGBToLinear(kPalette[i][1] / 255.f), SRGBToLinear(kPalette[i][2] / 255.f));
		src += buf;
	}
	src += ");\n";
	src += kVillageSurfaceBody;
	return src;
}

