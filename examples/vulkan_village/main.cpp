const int kFacades[] = {C_OCHRE, C_GOLD, C_PALE_YELLOW, C_ORANGE, C_TERRACOTTA, C_DEEP_RED, C_SALMON, C_PINK, C_PEACH,
	C_CORAL, C_CREAM, C_OCHRE, C_SALMON, C_GOLD, C_ORANGE, C_PEACH, C_SAGE, C_SKY, C_WARM_WHITE};
const int kShutters[] = {C_SHUT_GREEN, C_SHUT_GREEN, C_SHUT_DARK, C_SHUT_DARK, C_SHUT_TEAL, C_SHUT_BROWN, C_SHUT_BLUE};
const int kRoofs[] = {C_ROOF_TERRA, C_ROOF_TERRA, C_ROOF_DARK, C_ROOF_SLATE, C_ROOF_BROWN, C_ROOF_SLATE};
const int kAwnings[] = {C_AWN_RED, C_AWN_GREEN, C_AWN_YELLOW, C_AWN_BLUE};
const int kCloths[] = {C_TRIM_WHITE, C_TRIM_WHITE, C_CLOTH_BLUE, C_CLOTH_PINK, C_PALE_YELLOW, C_SKY};

template <size_t N> int Pick(Rng& r, const int (&a)[N]) { return a[r.I((int)N)]; }

// Window centred on (x, bottom..bottom+h) of the facade (z = 0).
void Window(Builder& b, Rng& r, float x, float y0, float w, float h, int shutter, int trim, bool shutters, bool laundryRight, float nextX)
{
	const float hw = w * 0.5f;
	// Glass, frame and sill.
	b.Box({x - hw, y0, -0.05f}, {x + hw, y0 + h, 0.03f}, C_GLASS, M_GLASS);
	const float t = 0.08f;
	b.Box({x - hw - t, y0 - 0.02f, 0.f}, {x - hw, y0 + h + t, 0.06f}, trim, M_PLAIN);
	b.Box({x + hw, y0 - 0.02f, 0.f}, {x + hw + t, y0 + h + t, 0.06f}, trim, M_PLAIN);
	b.Box({x - hw, y0 + h, 0.f}, {x + hw, y0 + h + t, 0.06f}, trim, M_PLAIN);
	b.Box({x - hw - 0.14f, y0 - 0.1f, 0.f}, {x + hw + 0.14f, y0, 0.16f}, trim, M_PLAIN);
	if (shutters)
	{
		if (r.P(0.72f))
		{
			// Open, against the wall on both sides.
			b.Box({x - hw - t - w * 0.52f, y0, 0.02f}, {x - hw - t - 0.02f, y0 + h + 0.02f, 0.08f}, shutter, M_SLATS);
			b.Box({x + hw + t + 0.02f, y0, 0.02f}, {x + hw + t + w * 0.52f, y0 + h + 0.02f, 0.08f}, shutter, M_SLATS);
		}
		else if (r.P(0.5f))
			b.Box({x - hw, y0, 0.0f}, {x + hw, y0 + h, 0.07f}, shutter, M_SLATS); // closed
		else
		{
			// Half open: one leaf closed, the other against the wall.
			b.Box({x - hw, y0, 0.0f}, {x, y0 + h, 0.07f}, shutter, M_SLATS);
			b.Box({x + hw + t + 0.02f, y0, 0.02f}, {x + hw + t + w * 0.52f, y0 + h + 0.02f, 0.08f}, shutter, M_SLATS);
		}
	}
	if (r.P(0.16f)) b.Box({x - hw - 0.05f, y0 - 0.32f, 0.f}, {x + hw + 0.05f, y0 - 0.1f, 0.28f}, C_PLANTER, M_FLOWERS);
	// Laundry line towards the next window.
	if (laundryRight)
	{
		const float ly = y0 - 0.3f, z = 0.38f;
		const float xa = x + hw + 0.1f, xb = nextX - hw - 0.1f;
		if (xb - xa > 0.5f)
		{
			b.Box({xa, ly - 0.012f, z - 0.012f}, {xb, ly + 0.012f, z + 0.012f}, C_IRON, M_PLAIN);
			b.Box({xa - 0.02f, ly - 0.03f, 0.f}, {xa + 0.02f, ly + 0.03f, z}, C_IRON, M_PLAIN);
			b.Box({xb - 0.02f, ly - 0.03f, 0.f}, {xb + 0.02f, ly + 0.03f, z}, C_IRON, M_PLAIN);
			for (float cx = xa + 0.1f; cx < xb - 0.3f;)
			{
				const float cw = r.R(0.25f, 0.55f), ch = r.R(0.35f, 0.8f);
				if (cx + cw > xb - 0.05f) break;
				b.Box({cx, ly - ch, z - 0.015f}, {cx + cw, ly, z + 0.015f}, Pick(r, kCloths), M_PLAIN);
				cx += cw + r.R(0.05f, 0.25f);
			}
		}
	}
}

struct HouseParams
{
	float width, depth, height;
};

void BuildHouse(MeshData& mesh, const Frame& frame, const HouseParams& hp, uint32_t seed)
{
	Rng r(seed);
	Builder b{mesh, frame};
	const float W = hp.width, D = hp.depth, H = hp.height, hw = W * 0.5f;
	const int wall = Pick(r, kFacades);
	const int trim = r.P(0.6f) ? C_TRIM_WHITE : (r.P(0.5f) ? C_TRIM_CREAM : wall);
	const int shutter = Pick(r, kShutters);
	const int roof = Pick(r, kRoofs);

	// Body, buried a few metres (the ground slopes behind it).
	b.Box({-hw, -7.f, -D}, {hw, H, 0.f}, wall, M_PLASTER);
	// Stone or darker base.
	if (r.P(0.45f)) b.Box({-hw - 0.03f, -7.f, -D}, {hw + 0.03f, r.R(0.5f, 1.0f), 0.04f}, C_STONE, M_STONE, M_STONE);
	// String course between the ground floor and the first floor.
	if (r.P(0.5f)) b.Box({-hw - 0.02f, 3.15f, -0.05f}, {hw + 0.02f, 3.3f, 0.08f}, trim, M_PLAIN);
	// Corner quoins in the trim colour.
	if (r.P(0.3f))
	{
		b.Box({-hw - 0.02f, 0.f, -0.3f}, {-hw + 0.3f, H, 0.04f}, trim, M_PLAIN);
		b.Box({hw - 0.3f, 0.f, -0.3f}, {hw + 0.02f, H, 0.04f}, trim, M_PLAIN);
	}

	// ---- Roof ----
	const float o = 0.35f, k = r.R(0.36f, 0.5f), th = 0.16f;
	const int roofType = r.F() < 0.1f ? 2 : (r.P(0.55f) ? 0 : 1);
	b.Box({-hw - 0.12f, H - 0.32f, -D - 0.12f}, {hw + 0.12f, H, 0.12f}, trim, M_PLAIN); // cornice
	float ridgeTop = H;
	if (roofType == 0)
	{
		// Ridge parallel to the facade.
		const float R = H + (D * 0.5f + o) * k;
		ridgeTop = R;
		b.Slab({-hw - o, H, o}, {hw + o, H, o}, {hw + o, R, -D * 0.5f}, {-hw - o, R, -D * 0.5f}, th, roof, M_ROOF, M_PLAIN);
		b.Slab({-hw - o, H, -D - o}, {hw + o, H, -D - o}, {hw + o, R, -D * 0.5f}, {-hw - o, R, -D * 0.5f}, th, roof, M_ROOF, M_PLAIN);
		for (float s : {-1.f, 1.f})
		{
			const V3 gable[5] = {{s * hw, H - 0.01f, 0.f}, {s * hw, H + o * k - th, 0.f}, {s * hw, R - th, -D * 0.5f},
				{s * hw, H + o * k - th, -D}, {s * hw, H - 0.01f, -D}};
			b.Poly(gable, 5, {s, 0.f, 0.f}, wall, M_PLASTER);
		}
		b.Box({-hw - o, R - 0.06f, -D * 0.5f - 0.12f}, {hw + o, R + 0.1f, -D * 0.5f + 0.12f}, roof, M_PLAIN);
	}
	else if (roofType == 1)
	{
		// Ridge perpendicular to the facade: a gable towards the sea.
		const float R = H + (hw + o) * k;
		ridgeTop = R;
		b.Slab({-hw - o, H, o}, {-hw - o, H, -D - o}, {0.f, R, -D - o}, {0.f, R, o}, th, roof, M_ROOF, M_PLAIN);
		b.Slab({hw + o, H, o}, {hw + o, H, -D - o}, {0.f, R, -D - o}, {0.f, R, o}, th, roof, M_ROOF, M_PLAIN);
		for (float zz : {0.f, -D})
		{
			const V3 gable[5] = {{-hw, H - 0.01f, zz}, {-hw, H + o * k - th, zz}, {0.f, R - th, zz}, {hw, H + o * k - th, zz},
				{hw, H - 0.01f, zz}};
			b.Poly(gable, 5, {0.f, 0.f, zz == 0.f ? 1.f : -1.f}, wall, M_PLASTER);
		}
		b.Box({-0.12f, R - 0.06f, -D - o}, {0.12f, R + 0.1f, o}, roof, M_PLAIN);
		// Small round window in the gable.
		if (R - H > 1.6f && r.P(0.6f)) b.Box({-0.28f, H + 0.35f, 0.f}, {0.28f, H + 0.9f, 0.03f}, C_GLASS, M_GLASS);
	}
	else
	{
		// Roof terrace with a parapet and plants.
		b.Box({-hw, H, -D}, {hw, H + 0.08f, 0.f}, C_PAVING, M_PAVING);
		b.Box({-hw, H, -0.25f}, {hw, H + 0.95f, 0.f}, wall, M_PLASTER);
		b.Box({-hw, H, -D}, {-hw + 0.25f, H + 0.95f, 0.f}, wall, M_PLASTER);
		b.Box({hw - 0.25f, H, -D}, {hw, H + 0.95f, 0.f}, wall, M_PLASTER);
		b.Box({-hw - 0.05f, H + 0.95f, -D}, {hw + 0.05f, H + 1.05f, 0.05f}, trim, M_PLAIN);
		for (int i = 0; i < 3; ++i)
		{
			const float x = r.R(-hw + 0.6f, hw - 0.6f), z = r.R(-D + 0.6f, -0.8f);
			b.BoxC({x, H + 0.35f, z}, {0.3f, 0.3f, 0.3f}, C_PLANTER, M_FLOWERS);
		}
		ridgeTop = H + 1.f;
	}
	// Chimney.
	if (roofType != 2 && r.P(0.55f))
	{
		const float cx = r.R(-hw + 0.6f, hw - 0.6f), cz = roofType == 0 ? -D * 0.5f - 0.6f : r.R(-D + 0.8f, -1.f);
		const float cx2 = roofType == 1 ? (cx < 0.f ? cx * 0.5f : cx * 0.5f) : cx;
		b.Box({cx2 - 0.28f, ridgeTop - 1.4f, cz - 0.28f}, {cx2 + 0.28f, ridgeTop + 0.75f, cz + 0.28f}, wall, M_PLASTER);
		b.Box({cx2 - 0.38f, ridgeTop + 0.75f, cz - 0.38f}, {cx2 + 0.38f, ridgeTop + 0.85f, cz + 0.38f}, roof, M_PLAIN, -1, false);
		b.Box({cx2 - 0.2f, ridgeTop + 0.85f, cz - 0.2f}, {cx2 + 0.2f, ridgeTop + 1.0f, cz + 0.2f}, roof, M_PLAIN);
	}

	// ---- Facade ----
	const int columns = std::max(1, (int)((W - 0.4f) / 1.85f));
	const float step = W / (float)columns;
	const float winW = std::min(0.8f, step * 0.42f);
	std::vector<float> xs;
	for (int c = 0; c < columns; ++c) xs.push_back(-hw + step * ((float)c + 0.5f));
	const bool laundryHouse = r.P(0.35f);
	// Upper floors.
	int floor = 0;
	for (float y = 3.3f; y + 2.6f <= H - 0.3f; y += 2.9f, ++floor)
	{
		const bool balconyFloor = floor == 0 && columns >= 2 && r.P(0.25f);
		const int balconyCol = r.I(columns);
		for (int c = 0; c < columns; ++c)
		{
			const float x = xs[(size_t)c];
			const bool laundry = laundryHouse && c + 1 < columns && r.P(0.4f);
			if (balconyFloor && c == balconyCol)
			{
				// French window and a balcony with an iron railing.
				Window(b, r, x, y + 0.05f, winW + 0.1f, 2.1f, shutter, trim, true, false, 0.f);
				const float bw = winW * 0.5f + 0.55f;
				b.Box({x - bw, y - 0.12f, 0.f}, {x + bw, y + 0.05f, 0.75f}, C_STONE, M_PLAIN, -1, false);
				b.Box({x - bw, y + 0.95f, 0.68f}, {x + bw, y + 1.0f, 0.73f}, C_IRON, M_PLAIN);
				b.Box({x - bw, y + 0.95f, 0.f}, {x - bw + 0.05f, y + 1.0f, 0.73f}, C_IRON, M_PLAIN);
				b.Box({x + bw - 0.05f, y + 0.95f, 0.f}, {x + bw, y + 1.0f, 0.73f}, C_IRON, M_PLAIN);
				for (float bx = x - bw + 0.06f; bx < x + bw - 0.04f; bx += 0.13f)
					b.Box({bx - 0.012f, y + 0.05f, 0.69f}, {bx + 0.012f, y + 0.95f, 0.71f}, C_IRON, M_PLAIN);
				if (r.P(0.6f)) b.BoxC({x - bw + 0.3f, y + 0.3f, 0.45f}, {0.22f, 0.25f, 0.18f}, C_PLANTER, M_FLOWERS);
				continue;
			}
			Window(b, r, x, y + 0.75f, winW, 1.35f, shutter, trim, true, laundry, c + 1 < columns ? xs[(size_t)c + 1] : 0.f);
		}
	}
	// Ground floor: a door, a shop or small windows.
	const int doorCol = r.I(columns);
	const bool shop = columns >= 2 && r.P(0.35f);
	const int shopCol = (doorCol + 1) % columns;
	for (int c = 0; c < columns; ++c)
	{
		const float x = xs[(size_t)c];
		if (c == doorCol)
		{
			const float dw = std::min(0.62f, step * 0.36f);
			b.Box({x - dw, 0.f, -0.08f}, {x + dw, 2.35f, 0.03f}, r.P(0.5f) ? C_DOOR : C_DOOR_DARK, M_WOOD);
			b.Box({x - dw - 0.16f, 0.f, 0.f}, {x - dw, 2.55f, 0.07f}, C_STONE, M_PLAIN);
			b.Box({x + dw, 0.f, 0.f}, {x + dw + 0.16f, 2.55f, 0.07f}, C_STONE, M_PLAIN);
			b.Box({x - dw - 0.16f, 2.35f, 0.f}, {x + dw + 0.16f, 2.6f, 0.07f}, C_STONE, M_PLAIN);
			b.Box({x - dw - 0.2f, -0.2f, 0.f}, {x + dw + 0.2f, 0.12f, 0.45f}, C_STONE, M_STONE, M_PAVING); // step
			if (r.P(0.4f)) b.BoxC({x + dw + 0.45f, 0.3f, 0.3f}, {0.2f, 0.3f, 0.2f}, C_PLANTER, M_FLOWERS);
		}
		else if (shop && c == shopCol)
		{
			const float sw = std::min(1.2f, step * 0.46f);
			b.Box({x - sw, 0.f, -0.08f}, {x + sw, 2.4f, 0.03f}, C_GLASS, M_GLASS);
			b.Box({x - sw - 0.1f, 2.4f, 0.f}, {x + sw + 0.1f, 2.55f, 0.06f}, C_DOOR, M_WOOD);
			// Striped awning.
			b.Slab({x - sw - 0.25f, 3.0f, 0.f}, {x + sw + 0.25f, 3.0f, 0.f}, {x + sw + 0.25f, 2.45f, 1.3f},
				{x - sw - 0.25f, 2.45f, 1.3f}, 0.04f, Pick(r, kAwnings), M_STRIPES, M_STRIPES);
		}
		else
		{
			const float ww = winW * 0.45f;
			b.Box({x - ww, 1.0f, -0.05f}, {x + ww, 2.2f, 0.03f}, C_GLASS, M_GLASS);
			b.Box({x - ww - 0.1f, 0.9f, 0.f}, {x + ww + 0.1f, 1.0f, 0.12f}, trim, M_PLAIN);
			for (int i = 0; i < 3; ++i)
			{
				const float bx = x - ww + (float)(i + 1) * ww * 0.5f;
				b.Box({bx - 0.015f, 1.0f, 0.05f}, {bx + 0.015f, 2.2f, 0.08f}, C_IRON, M_PLAIN);
			}
		}
	}
}

