// One texel per ~0.4 m of the whole landscape: sand, sea bed, terraces, woods, rock.
HRL_id MakeGroundTexture()
{
	const int size = 2048;
	std::vector<unsigned char> rgba((size_t)size * size * 4);
	for (int py = 0; py < size; ++py)
		for (int px = 0; px < size; ++px)
		{
			const float x = ((float)px / (float)(size - 1) - 0.5f) * kLandSize;
			// HRL stores the first row given at the top of the picture (v = 1): row 0 is the far +Z edge.
			const float z = (0.5f - (float)py / (float)(size - 1)) * kLandSize + kLandCenterZ;
			const float h = TerrainHeight(x, z);
			const Polar pol = ToPolar(x, z);
			const float deg = pol.theta * 180.f / kPi;
			const float grain = ValueNoise(x * 1.7f, z * 1.7f);
			float col[3];
			auto set = [&](float r, float g, float b) { col[0] = r; col[1] = g; col[2] = b; };
			auto mixc = [&](float r, float g, float b, float t)
			{
				col[0] = Mix(col[0], r, t); col[1] = Mix(col[1], g, t); col[2] = Mix(col[2], b, t);
			};
			const float sandK = 0.92f + 0.12f * grain;
			if (h < 0.f)
			{
				// Sea bed: pale sand, then darker sand and sea grass deeper.
				set(0.93f * sandK, 0.86f * sandK, 0.66f * sandK);
				mixc(0.55f, 0.66f, 0.50f, Smooth(1.5f, 7.f, -h));
				mixc(0.30f, 0.45f, 0.30f, Smooth(0.55f, 0.75f, Fbm(x / 12.f, z / 12.f, 3)) * Smooth(2.f, 5.f, -h) * 0.7f);
			}
			else
			{
				const V3 n = TerrainNormal(x, z);
				const float slope = std::acos(Clamp(n.y, 0.f, 1.f)) * 180.f / kPi;
				// Grass of the terraces, with the stone walls of the terraces as stripes.
				const float g = Fbm(x / 20.f, z / 20.f, 3);
				set(0.50f + 0.12f * g, 0.64f + 0.06f * g, 0.18f);
				mixc(0.68f, 0.70f, 0.24f, Smooth(0.55f, 0.75f, Fbm(x / 40.f + 3.f, z / 40.f, 3)) * 0.7f);
				const float terrace = h / 2.4f + Fbm(x / 30.f, z / 30.f, 2) * 0.6f;
				const float tf = terrace - std::floor(terrace);
				mixc(0.36f, 0.42f, 0.16f, Smooth(0.86f, 0.93f, tf) * 0.55f);
				mixc(0.62f, 0.58f, 0.52f, Smooth(0.94f, 0.99f, tf) * 0.6f);
				// Woods (darker, under the trees).
				mixc(0.20f, 0.34f, 0.10f, ForestDensity(x, z) * Smooth(10.f, 25.f, h) * 0.85f);
				// Rock on the steep slopes.
				mixc(0.66f, 0.60f, 0.64f, Smooth(44.f, 58.f, slope));
				// Village: dirt and paving between the houses.
				const float edge = VillageEdgeDeg(pol.d);
				mixc(0.70f * sandK, 0.60f * sandK, 0.48f * sandK, Smooth(edge + 2.f, edge - 2.f, std::abs(deg)) * Smooth(92.f, 84.f, pol.d));
				// Sand along the water and on the beach.
				const float beach = BeachMask(deg) * Smooth(24.f, 18.f, pol.d);
				mixc(0.93f * sandK, 0.85f * sandK, 0.64f * sandK, std::max(Smooth(1.2f, 0.4f, h), beach));
				// Wet sand at the water line.
				mixc(0.70f, 0.62f, 0.46f, Smooth(0.45f, 0.05f, h));
			}
			unsigned char* p = &rgba[((size_t)py * size + px) * 4];
			for (int c = 0; c < 3; ++c) p[c] = (unsigned char)Clamp(col[c] * 255.f, 0.f, 255.f);
			p[3] = 255;
		}
	return HRL_CreateTextureFromPixels(rgba.data(), size, size);
}

// Depth of the sea bed under the water (0 : shore, 1 : 12 m and more), read by the water shader.
