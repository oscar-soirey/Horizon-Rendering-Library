int RunWindow(Options& opt)
{
	if (!glfwInit()) { std::fprintf(stderr, "GLFW initialisation failed\n"); return 1; }
	if (!glfwVulkanSupported()) { std::fprintf(stderr, "No Vulkan loader / driver found\n"); glfwTerminate(); return 1; }
	glfwWindowHint(GLFW_CLIENT_API, GLFW_NO_API);
	GLFWwindow* window = glfwCreateWindow(opt.width, opt.height, "HRL - Vulkan village", nullptr, nullptr);
	if (!window) { glfwTerminate(); return 1; }

	uint32_t extensionCount = 0;
	const char** extensions = glfwGetRequiredInstanceExtensions(&extensionCount);
	HRL_RegisterErrorCallback(OnError);
	HRL_Vulkan_SetInstanceExtensions(extensions, extensionCount);
	HRL_Vulkan_SetSurfaceCallback(CreateSurface, window);
	HRL_Init(HRL_VULKAN);
	int fbw = 0, fbh = 0;
	glfwGetFramebufferSize(window, &fbw, &fbh);
	HRL_InitContext((HRL_uint)fbw, (HRL_uint)fbh, nullptr);
	if (g_errors) { glfwTerminate(); return 1; }
	std::printf("GPU: %s | hardware ray tracing: %s\n", HRL_Vulkan_GetDeviceName(), HRL_Vulkan_IsRayTracingSupported() ? "yes" : "no");

	World w;
	BuildWorld(w, opt);
	const double start = glfwGetTime();
	double lastTime = start, lastX = 0, lastY = 0, titleTime = 0;
	bool looking = false, rWasDown = false, pWasDown = false;
	int shot = 0, frame = 0, titleFrames = 0;
	while (!glfwWindowShouldClose(window) && (opt.frames == 0 || frame++ < opt.frames))
	{
		glfwPollEvents();
		const double now = glfwGetTime();
		const float dt = (float)(now - lastTime);
		lastTime = now;
		titleTime += dt;
		++titleFrames;
		if (titleTime >= 1.0)
		{
			char title[128];
			std::snprintf(title, sizeof(title), "HRL - Vulkan village - %d FPS", titleFrames);
			glfwSetWindowTitle(window, title);
			titleTime = 0.0;
			titleFrames = 0;
		}

		int fw = 0, fh = 0;
		glfwGetFramebufferSize(window, &fw, &fh);
		if (fw != fbw || fh != fbh)
		{
			fbw = fw; fbh = fh;
			HRL_WindowResizeCallback(fw, fh);
		}
		if (fw == 0 || fh == 0) { glfwWaitEvents(); continue; }

		if (glfwGetKey(window, GLFW_KEY_ESCAPE) == GLFW_PRESS) glfwSetWindowShouldClose(window, 1);
		for (int i = 1; i <= kViewCount; ++i)
			if (glfwGetKey(window, GLFW_KEY_0 + i) == GLFW_PRESS) w.view = Viewpoint(i);
		double mx = 0, my = 0;
		glfwGetCursorPos(window, &mx, &my);
		const bool rmb = glfwGetMouseButton(window, GLFW_MOUSE_BUTTON_RIGHT) == GLFW_PRESS;
		if (rmb && looking)
		{
			w.view.yaw += (float)(mx - lastX) * 0.15f;
			w.view.pitch = Clamp(w.view.pitch - (float)(my - lastY) * 0.15f, -89.f, 89.f);
		}
		looking = rmb;
		lastX = mx; lastY = my;

		const float p = w.view.pitch * kPi / 180.f, y = w.view.yaw * kPi / 180.f;
		const float fx = std::cos(p) * std::cos(y), fy = std::sin(p), fz = std::cos(p) * std::sin(y);
		const float rx = -std::sin(y), rz = std::cos(y);
		const float speed = (glfwGetKey(window, GLFW_KEY_LEFT_SHIFT) == GLFW_PRESS ? 40.f : 8.f) * dt;
		auto key = [&](int k) { return glfwGetKey(window, k) == GLFW_PRESS ? 1.f : 0.f; };
		const float forward = key(GLFW_KEY_W) - key(GLFW_KEY_S), right = key(GLFW_KEY_D) - key(GLFW_KEY_A);
		const float up = key(GLFW_KEY_E) - key(GLFW_KEY_Q);
		w.view.x += (fx * forward + rx * right) * speed;
		w.view.y += (fy * forward + up) * speed;
		w.view.z += (fz * forward + rz * right) * speed;

		const bool rDown = glfwGetKey(window, GLFW_KEY_R) == GLFW_PRESS;
		if (rDown && !rWasDown)
		{
			HRL_Vulkan_SetRayTracedShadows(!HRL_Vulkan_GetRayTracedShadows());
			std::printf("ray traced shadows: %s\n", HRL_Vulkan_GetRayTracedShadows() ? "on" : "off (shadow maps)");
		}
		rWasDown = rDown;
		const bool pDown = glfwGetKey(window, GLFW_KEY_P) == GLFW_PRESS;
		if (pDown && !pWasDown)
		{
			const std::string path = "hrl_village_" + std::to_string(shot++) + ".png";
			HRL_TakeScreenshot(w.scene, path.c_str());
			std::printf("screenshot: %s\n", path.c_str());
		}
		pWasDown = pDown;

		UpdateWorld(w, (float)(now - start));
		HRL_BeginFrame();
		HRL_EndFrame();
	}
	HRL_Shutdown();
	glfwDestroyWindow(window);
	glfwTerminate();
	return g_errors ? 1 : 0;
}
