struct MeshData
{
	std::vector<HRL_Vertex3D> vertices;
	std::vector<HRL_uint> indices;
};

HRL_Vertex3D MakeVertex(V3 p, V3 n, float u, float v, V3 t)
{
	HRL_Vertex3D r{};
	r.position[0] = p.x; r.position[1] = p.y; r.position[2] = p.z;
	r.normal[0] = n.x; r.normal[1] = n.y; r.normal[2] = n.z;
	r.uv[0] = u; r.uv[1] = v;
	r.tangent[0] = t.x; r.tangent[1] = t.y; r.tangent[2] = t.z;
	const V3 b = Cross(n, t);
	r.bitangent[0] = b.x; r.bitangent[1] = b.y; r.bitangent[2] = b.z;
	return r;
}

// Local frame of a building: x along the facade, y up, z out of the facade.
struct Frame
{
	V3 origin;
	float c = 1.f, s = 0.f; // cos / sin of the yaw that turns +z into the facing direction

	static Frame Facing(V3 origin, float fx, float fz)
	{
		const float l = std::sqrt(fx * fx + fz * fz);
		Frame f;
		f.origin = origin;
		f.s = fx / l;
		f.c = fz / l;
		return f;
	}
	V3 Dir(V3 l) const { return {l.x * c + l.z * s, l.y, -l.x * s + l.z * c}; }
	V3 Point(V3 l) const { return origin + Dir(l); }
};

// Flat shaded faces, coloured with the palette.
struct Builder
{
	MeshData& m;
	Frame f;

	// Convex planar polygon (local coordinates). `hint` points out of the face:
	// the winding is chosen so the face is counter-clockwise seen from there.
	void Poly(const V3* local, int count, V3 hint, int slot, int mode)
	{
		V3 p[8];
		for (int k = 0; k < count; ++k) p[k] = f.Point(local[k]);
		// Newell normal: robust for any convex polygon.
		V3 n;
		for (int k = 0; k < count; ++k)
		{
			const V3 a = p[k], b = p[(k + 1) % count];
			n.x += (a.y - b.y) * (a.z + b.z);
			n.y += (a.z - b.z) * (a.x + b.x);
			n.z += (a.x - b.x) * (a.y + b.y);
		}
		if (Length(n) < 1e-9f) return;
		n = Normalize(n);
		if (Dot(n, f.Dir(hint)) < 0.f)
		{
			std::reverse(p, p + count);
			n = -n;
		}
		V3 t = p[1] - p[0];
		t = Normalize(t - n * Dot(n, t));
		const float u = ((float)slot + 0.5f) / (float)kPaletteSlots, v = (float)mode + 0.5f;
		const HRL_uint base = (HRL_uint)m.vertices.size();
		for (int k = 0; k < count; ++k) m.vertices.push_back(MakeVertex(p[k], n, u, v, t));
		for (int k = 1; k + 1 < count; ++k) m.indices.insert(m.indices.end(), {base, base + (HRL_uint)k, base + (HRL_uint)k + 1});
	}
	void Quad(V3 a, V3 b, V3 c, V3 d, V3 hint, int slot, int mode)
	{
		const V3 p[4] = {a, b, c, d};
		Poly(p, 4, hint, slot, mode);
	}
	// Axis aligned (in the local frame) box. skipBottom: buried faces are not built.
	void Box(V3 mn, V3 mx, int slot, int mode, int topMode = -1, bool skipBottom = true)
	{
		const int tm = topMode < 0 ? mode : topMode;
		Quad({mn.x, mn.y, mx.z}, {mx.x, mn.y, mx.z}, {mx.x, mx.y, mx.z}, {mn.x, mx.y, mx.z}, {0, 0, 1}, slot, mode);
		Quad({mn.x, mn.y, mn.z}, {mx.x, mn.y, mn.z}, {mx.x, mx.y, mn.z}, {mn.x, mx.y, mn.z}, {0, 0, -1}, slot, mode);
		Quad({mx.x, mn.y, mn.z}, {mx.x, mn.y, mx.z}, {mx.x, mx.y, mx.z}, {mx.x, mx.y, mn.z}, {1, 0, 0}, slot, mode);
		Quad({mn.x, mn.y, mn.z}, {mn.x, mn.y, mx.z}, {mn.x, mx.y, mx.z}, {mn.x, mx.y, mn.z}, {-1, 0, 0}, slot, mode);
		Quad({mn.x, mx.y, mn.z}, {mx.x, mx.y, mn.z}, {mx.x, mx.y, mx.z}, {mn.x, mx.y, mx.z}, {0, 1, 0}, slot, tm);
		if (!skipBottom) Quad({mn.x, mn.y, mn.z}, {mx.x, mn.y, mn.z}, {mx.x, mn.y, mx.z}, {mn.x, mn.y, mx.z}, {0, -1, 0}, slot, mode);
	}
	void BoxC(V3 c, V3 h, int slot, int mode, int topMode = -1, bool skipBottom = false)
	{
		Box(c - h, c + h, slot, mode, topMode, skipBottom);
	}
	// Quad top surface with a thickness below it (roof panes, awnings).
	void Slab(V3 a, V3 b, V3 c, V3 d, float thickness, int slot, int topMode, int sideMode, int sideSlot = -1)
	{
		const V3 down{0.f, -thickness, 0.f};
		const V3 center = (a + b + c + d) * 0.25f;
		const V3 top[4] = {a, b, c, d};
		Quad(a, b, c, d, {0, 1, 0}, slot, topMode);
		Quad(a + down, b + down, c + down, d + down, {0, -1, 0}, sideSlot < 0 ? slot : sideSlot, sideMode);
		for (int k = 0; k < 4; ++k)
		{
			const V3 p = top[k], q = top[(k + 1) % 4];
			const V3 mid = (p + q) * 0.5f;
			Quad(p, q, q + down, p + down, mid - center, sideSlot < 0 ? slot : sideSlot, sideMode);
		}
	}
	// Vertical prism with `sides` faces (approximates cylinders).
	void Prism(V3 base, float radius, float height, int sides, int slot, int mode, bool cap = true)
	{
		for (int k = 0; k < sides; ++k)
		{
			const float a0 = (float)k / (float)sides * 2.f * kPi, a1 = (float)(k + 1) / (float)sides * 2.f * kPi;
			const V3 p0{base.x + std::cos(a0) * radius, base.y, base.z + std::sin(a0) * radius};
			const V3 p1{base.x + std::cos(a1) * radius, base.y, base.z + std::sin(a1) * radius};
			const V3 up{0.f, height, 0.f};
			const float am = (a0 + a1) * 0.5f;
			Quad(p0, p1, p1 + up, p0 + up, {std::cos(am), 0.f, std::sin(am)}, slot, mode);
		}
		if (cap)
		{
			V3 ring[8];
			const int n = std::min(sides, 8);
			for (int k = 0; k < n; ++k)
			{
				const float a = (float)k / (float)n * 2.f * kPi;
				ring[k] = {base.x + std::cos(a) * radius, base.y + height, base.z + std::sin(a) * radius};
			}
			Poly(ring, n, {0, 1, 0}, slot, mode);
		}
	}
};

// Smooth closed surface from a sphere (no seam: the U/V of the vertices carry
// the palette, or planar texture coordinates). `shape` moves each unit
// direction to its position; normals are averaged over the triangles.
template <class Shape, class UV>
void AddSmoothSphere(MeshData& m, int rings, int sectors, Shape shape, UV uvOf)
{
	const HRL_uint base = (HRL_uint)m.vertices.size();
	std::vector<V3> pos;
	pos.push_back(shape(V3{0.f, 1.f, 0.f}));
	for (int r = 1; r < rings; ++r)
	{
		const float theta = (float)r / (float)rings * kPi;
		for (int s = 0; s < sectors; ++s)
		{
			const float phi = (float)s / (float)sectors * 2.f * kPi;
			pos.push_back(shape(V3{std::sin(theta) * std::cos(phi), std::cos(theta), std::sin(theta) * std::sin(phi)}));
		}
	}
	pos.push_back(shape(V3{0.f, -1.f, 0.f}));
	const HRL_uint south = (HRL_uint)pos.size() - 1;
	auto ring = [&](int r, int s) -> HRL_uint { return 1u + (HRL_uint)((r - 1) * sectors + (s % sectors)); };
	std::vector<HRL_uint> idx;
	for (int s = 0; s < sectors; ++s) idx.insert(idx.end(), {0u, ring(1, s + 1), ring(1, s)});
	for (int r = 1; r < rings - 1; ++r)
		for (int s = 0; s < sectors; ++s)
		{
			const HRL_uint a = ring(r, s), b = ring(r, s + 1), c = ring(r + 1, s), d = ring(r + 1, s + 1);
			idx.insert(idx.end(), {a, b, c, b, d, c});
		}
	for (int s = 0; s < sectors; ++s) idx.insert(idx.end(), {south, ring(rings - 1, s), ring(rings - 1, s + 1)});
	std::vector<V3> nrm(pos.size());
	for (size_t k = 0; k < idx.size(); k += 3)
	{
		const V3 a = pos[idx[k]], b = pos[idx[k + 1]], c = pos[idx[k + 2]];
		const V3 n = Cross(b - a, c - a);
		for (int j = 0; j < 3; ++j) nrm[idx[k + j]] = nrm[idx[k + j]] + n;
	}
	for (size_t k = 0; k < pos.size(); ++k)
	{
		const V3 n = Normalize(nrm[k]);
		V3 t = Cross(V3{0.f, 1.f, 0.f}, n);
		if (Length(t) < 1e-4f) t = {1.f, 0.f, 0.f};
		float u = 0.f, v = 0.f;
		uvOf(pos[k], u, v);
		m.vertices.push_back(MakeVertex(pos[k], n, u, v, Normalize(t)));
	}
	for (HRL_uint i : idx) m.indices.push_back(base + i);
}

// ---------------------------------------------------------------------------
// Terrain: a cove open towards +Z, the village climbing the slope around it.
// Polar coordinates around the centre of the cove: angle 0 points inland (-Z).
// ---------------------------------------------------------------------------
const float kCoveX = 0.f, kCoveZ = 20.f;
const float kLandSize = 768.f, kLandCenterZ = -40.f;
const int kLandSamples = 769;
// Piazza on the water front, in the middle of the village.
const float kPiazzaX0 = -16.f, kPiazzaX1 = 16.f, kPiazzaZ0 = -34.f, kPiazzaZ1 = -20.f, kPiazzaY = 1.3f;

float ShoreRadius(float theta) { return 34.f + 5.f * std::sin(3.f * theta + 1.f) + 3.f * std::sin(7.f * theta + 2.3f); }

struct Polar
{
	float r, theta, d; // distance to the centre of the cove, angle (radians), distance inland from the shore
};
Polar ToPolar(float x, float z)
{
	const float dx = x - kCoveX, dz = z - kCoveZ;
	Polar p;
	p.r = std::sqrt(dx * dx + dz * dz);
	p.theta = std::atan2(dx, -dz);
	p.d = p.r - ShoreRadius(p.theta);
	return p;
}
V3 FromPolar(float theta, float d)
{
	const float r = ShoreRadius(theta) + d;
	return {kCoveX + std::sin(theta) * r, 0.f, kCoveZ - std::cos(theta) * r};
}

float VillageMask(float thetaDeg) { return Smooth(84.f, 62.f, std::abs(thetaDeg)); }
// Angle where the rows of houses end (the upper rows are a little narrower).
float VillageEdgeDeg(float d) { return 70.f - 1.5f * std::max(0.f, d - 6.f) / 8.6f; }
float BeachMask(float thetaDeg) { return Smooth(18.f, 25.f, thetaDeg) * Smooth(46.f, 39.f, thetaDeg); }

float TerrainHeight(float x, float z)
{
	const Polar p = ToPolar(x, z);
	const float deg = p.theta * 180.f / kPi, at = std::abs(deg);
	const float d = p.d;
	// Sea bed: shallow along the shore, about 9 m in the middle of the cove.
	const float seabed = std::max(-0.5f + d * 0.3f, -9.f) + (Fbm(x / 14.f, z / 14.f, 3) - 0.5f) * 0.8f;
	// Village slope, then the hills behind it.
	// Low along the water front (quays), then the slope of the houses.
	float village = d < 10.f ? 0.6f + d * 0.22f : 2.8f + (d - 10.f) * 0.42f;
	if (d > 90.f) village += (d - 90.f) * (d - 90.f) * 0.0012f + (d - 90.f) * 0.12f;
	// Steep green hills on the sides of the cove.
	const float hill = 0.8f + d * 0.52f - std::max(0.f, d - 70.f) * 0.26f;
	float land = Mix(hill, village, VillageMask(deg));
	// Bumps of the hills (not along the shore).
	land += (Fbm(x / 130.f + 7.f, z / 130.f, 5) - 0.45f) * 34.f * Smooth(30.f, 140.f, d);
	land += (Fbm(x / 25.f, z / 25.f, 3) - 0.5f) * 3.f * Smooth(5.f, 40.f, d);
	// Rounded summits on the far ridges (their silhouette against the sky).
	land += (Fbm(x / 45.f + 3.f, z / 45.f, 4) - 0.45f) * 26.f * Smooth(110.f, 240.f, d);
	// The hills go down near the edges of the landscape, so its border is never seen.
	const float edge = std::min(kLandSize * 0.5f - std::abs(x), kLandSize * 0.5f - std::abs(z - kLandCenterZ));
	land = Mix(std::min(land, 4.f), land, Smooth(8.f, 120.f, edge));
	// Gentle beach.
	const float beach = BeachMask(deg) * Smooth(26.f, 14.f, d);
	land = Mix(land, 0.25f + d * 0.11f, beach);
	float h = d < 0.f ? seabed : Mix(std::min(seabed, land), land, Smooth(0.f, 2.f, d));
	if (d < 0.f && beach > 0.f) h = Mix(h, std::max(-0.3f + d * 0.12f, -9.f), beach);
	// Open sea towards +Z: the headlands slope down into the water.
	const float open = Smooth(98.f, 140.f, at);
	const float deep = std::max(-7.f - std::max(0.f, p.r - 30.f) * 0.2f, -18.f) + (Fbm(x / 30.f, z / 30.f, 3) - 0.5f) * 2.f;
	h = Mix(h, std::min(h, deep), open);
	// Flat piazza.
	const float px = Smooth(kPiazzaX0 - 4.f, kPiazzaX0, x) * Smooth(kPiazzaX1 + 4.f, kPiazzaX1, x);
	const float pz = Smooth(kPiazzaZ0 - 5.f, kPiazzaZ0, z) * Smooth(kPiazzaZ1 + 0.5f, kPiazzaZ1 - 0.5f, z);
	h = Mix(h, kPiazzaY - 0.05f, px * pz);
	return h;
}

V3 TerrainNormal(float x, float z)
{
	const float e = 1.f;
	const float hx = TerrainHeight(x + e, z) - TerrainHeight(x - e, z);
	const float hz = TerrainHeight(x, z + e) - TerrainHeight(x, z - e);
	return Normalize({-hx / (2.f * e), 1.f, -hz / (2.f * e)});
}

// Where the woods of the hills are (shared by the trees and the ground colour).
float ForestDensity(float x, float z) { return Smooth(0.36f, 0.52f, Fbm(x / 70.f + 40.f, z / 70.f, 4)); }

bool InPiazza(float x, float z, float margin)
{
	return x > kPiazzaX0 - margin && x < kPiazzaX1 + margin && z > kPiazzaZ0 - margin && z < kPiazzaZ1 + margin;
}

