MeshData MakeTrunk(float r0, float r1, float height, float leanX, int sides)
{
	MeshData m;
	for (int k = 0; k <= sides; ++k)
	{
		const float a = (float)k / (float)sides * 2.f * kPi, c = std::cos(a), s = std::sin(a);
		const V3 n{c, 0.15f, s}, t{-s, 0.f, c};
		m.vertices.push_back(MakeVertex({c * r0, -0.4f, s * r0}, Normalize(n), (float)k / sides * 2.f, 0.f, t));
		m.vertices.push_back(MakeVertex({c * r1 + leanX, height, s * r1}, Normalize(n), (float)k / sides * 2.f, height * 0.5f, t));
	}
	for (int k = 0; k < sides; ++k)
	{
		const HRL_uint a = 2u * (HRL_uint)k;
		m.indices.insert(m.indices.end(), {a, a + 1, a + 2, a + 2, a + 1, a + 3});
	}
	return m;
}

void AddBlob(MeshData& m, V3 center, V3 radii, uint32_t seed, float bumps)
{
	const float o = (float)(seed % 61) * 1.7f;
	AddSmoothSphere(m, 10, 16,
		[&](V3 d)
		{
			const float n = ValueNoise3(d.x * 2.2f + o, d.y * 2.2f, d.z * 2.2f - o) - 0.5f;
			const float k = 1.f + n * bumps;
			V3 p{d.x * radii.x * k, d.y * radii.y * k, d.z * radii.z * k};
			if (p.y < -radii.y * 0.45f) p.y = -radii.y * 0.45f + (p.y + radii.y * 0.45f) * 0.4f;
			return center + p;
		},
		[&](V3 p, float& u, float& v) { u = (p.x + p.z * 0.6f) * 0.22f; v = (p.y - p.z * 0.4f) * 0.22f; });
}

MeshData MakeRoundCanopy(uint32_t seed, float size)
{
	MeshData m;
	Rng r(seed);
	AddBlob(m, {0.f, 5.2f * size, 0.f}, V3{2.5f, 2.1f, 2.5f} * size, seed, 0.35f);
	for (int i = 0; i < 4; ++i)
	{
		const float a = (float)i / 4.f * 2.f * kPi + r.R(0.f, 1.f);
		AddBlob(m, V3{std::cos(a) * 1.7f, 4.4f + r.R(-0.3f, 0.6f), std::sin(a) * 1.7f} * size, V3{1.6f, 1.4f, 1.6f} * size, seed + 7u + (uint32_t)i, 0.4f);
	}
	AddBlob(m, V3{0.3f, 6.7f, -0.2f} * size, V3{1.5f, 1.3f, 1.5f} * size, seed + 3u, 0.4f);
	return m;
}

