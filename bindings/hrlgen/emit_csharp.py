"""C# emitter : P/Invoke (.NET 6+, unsafe code enabled).

HRL.Native  : exact C signatures (pointers, enums, delegates)
HRL.Hrl     : friendly methods (string, spans, out parameters, delegates kept alive)
"""
from .common import HEADER_NOTE, param_roles, sized_by, clean_name, enum_of, strip_prefix
from .parser import CType

_CS = {
    "void": "void", "int": "int", "unsigned int": "uint", "float": "float", "double": "double",
    "char": "byte", "unsigned char": "byte", "int8_t": "sbyte", "uint8_t": "byte", "int16_t": "short",
    "uint16_t": "ushort", "int32_t": "int", "uint32_t": "uint", "int64_t": "long", "uint64_t": "ulong",
    "size_t": "nuint", "bool": "byte", "short": "short",
}
_KEYWORDS = {"base", "object", "string", "params", "ref", "out", "in", "event", "checked", "fixed", "lock", "operator",
             "decimal", "delegate", "internal", "namespace", "readonly", "sizeof", "typeof", "default", "float", "int"}


def cs_name(n):
    n = clean_name(n)
    return "@" + n if n in _KEYWORDS else n


def cs_type(api, t):
    """Raw C# type of a C type."""
    if api.callback(t.base) and t.pointers == 0:
        return t.base
    base = t.base
    if base in api.aliases:
        r = api.resolve(CType(base))
        inner = _CS[r.base] if r.pointers == 0 else "void*"
        return inner + "*" * t.pointers
    if base in _CS:
        return _CS[base] + "*" * t.pointers
    if api.enum(base) or api.struct(base):
        return base + "*" * t.pointers
    raise ValueError("C#: unknown type %r" % t)


def xml_doc(doc, indent):
    if not doc:
        return []
    out = [indent + "/// <summary>"]
    for l in doc.splitlines():
        l = l.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        out.append(indent + "/// " + l)
    out.append(indent + "/// </summary>")
    return out


def emit(api, headers):
    files = {}
    o = []
    w = o.append
    w("// <auto-generated>")
    w("// " + HEADER_NOTE.format(headers=", ".join(headers), version=api.version))
    w("// </auto-generated>")
    w("#pragma warning disable CS1591, IDE1006")
    w("using System;")
    w("using System.Collections.Generic;")
    w("using System.Runtime.InteropServices;")
    w("using System.Text;")
    w("")
    w("namespace HRL")
    w("{")
    # enums
    for e in api.enums:
        o.extend(xml_doc(e.doc, "    "))
        w("    public enum %s : int" % e.name)
        w("    {")
        for n, v, d in e.values:
            o.extend(xml_doc(d, "        "))
            w("        %s = %d," % (n, v))
        w("    }")
        w("")
    # structs
    consts = api.int_names()
    for s in api.structs:
        o.extend(xml_doc(s.doc, "    "))
        w("    [StructLayout(LayoutKind.Sequential)]")
        w("    public unsafe struct %s" % s.name)
        w("    {")
        for f in s.fields:
            t = cs_type(api, f.type)
            if f.array:
                n = consts.get(f.array, f.array)
                if t in ("float", "int", "uint", "byte", "double", "short", "long"):
                    w("        public fixed %s %s[%s];" % (t, f.name, n))
                else:
                    raise ValueError("C#: array of %s" % t)
            else:
                w("        public %s %s;" % (t, f.name))
        w("    }")
        w("")
    # callbacks
    for c in api.callbacks:
        o.extend(xml_doc(c.doc, "    "))
        w("    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]")
        w("    public unsafe delegate %s %s(%s);" % (cs_type(api, c.ret), c.name,
                                                    ", ".join("%s %s" % (cs_type(api, p.type), cs_name(p.name)) for p in c.params)))
        w("")

    # Native ---------------------------------------------------------------
    w("    /// <summary>Raw P/Invoke declarations (exact C signatures).</summary>")
    w("    public static unsafe class Native")
    w("    {")
    w("        /// <summary>Name of the native library (hrldll.dll / libhrldll.so / libhrldll.dylib).</summary>")
    w('        public const string Library = "hrldll";')
    w("")
    for f in api.functions:
        if f.variadic:
            # P/Invoke cannot call C variadic functions portably (e.g. Apple ARM64) :
            # the API provides a non-variadic twin (HRL_AddScreenMessageText).
            w("        // %s : variadic, not bound (use its non-variadic twin)." % f.name)
            w("")
            continue
        params = ["%s %s" % (cs_type(api, p.type), cs_name(p.name)) for p in f.params]
        o.extend(xml_doc(f.doc, "        "))
        w('        [DllImport(Library, CallingConvention = CallingConvention.Cdecl, EntryPoint = "%s")]' % f.name)
        w("        public static extern %s %s(%s);" % (cs_type(api, f.ret), f.name, ", ".join(params)))
        w("")
    w("    }")
    w("")

    # Hrl (friendly) -----------------------------------------------------------
    w("    /// <summary>HRL API with .NET types : strings, spans, out parameters.</summary>")
    w("    public static unsafe class Hrl")
    w("    {")
    for c in api.constants:
        if c.kind == "string":
            w('        public const string %s = "%s";' % (c.name, c.value.replace('"', '\\"')))
        elif c.kind == "float":
            w("        public const float %s = %sf;" % (c.name, repr(c.value)))
        elif c.kind == "uint":
            w("        public const uint %s = %du;" % (c.name, c.value))
        else:
            w("        public const int %s = %d;" % (c.name, c.value))
    w("")
    w("        // Delegates passed to native code must stay alive while registered.")
    w("        static readonly Dictionary<string, Delegate> s_callbacks = new Dictionary<string, Delegate>();")
    w("")
    w("        static byte[] Utf8(string s) => s == null ? null : Encoding.UTF8.GetBytes(s + \"\\0\");")
    w("        static string FromUtf8(byte* p) => p == null ? null : Marshal.PtrToStringUTF8((IntPtr)p);")
    w("")
    for f in api.functions:
        if f.variadic:
            continue
        roles = param_roles(api, f)
        sizes = sized_by(roles)
        sig = []
        pre = []
        fixed = []
        call = []
        post = []
        for i, (p, r) in enumerate(zip(f.params, roles)):
            n = cs_name(p.name)
            raw = cs_type(api, p.type)
            t = api.resolve(p.type)
            if r == "size":
                bufs = sizes.get(i, [])
                call.append("(%s)_n%d" % (raw, bufs[0]) if bufs else "0")
                continue
            if f.variadic and i == len(f.params) - 1:
                call.append("_pf")  # printf format : always "%s"
                continue
            if r == "value":
                sig.append("%s %s" % (raw, n))
                call.append(n)
            elif r == "string":
                sig.append("string %s" % n)
                pre.append("var _b%d = Utf8(%s);" % (i, n))
                fixed.append("fixed (byte* _p%d = _b%d)" % (i, i))
                call.append("_p%d" % i)
            elif r == "bytes":
                sig.append("ReadOnlySpan<byte> %s" % n)
                pre.append("int _n%d = %s.Length;" % (i, n))
                fixed.append("fixed (byte* _p%d = %s)" % (i, n))
                call.append("(%s)_p%d" % (raw, i))
            elif r == "array":
                elem = raw[:-1]
                sig.append("ReadOnlySpan<%s> %s" % (elem, n))
                pre.append("int _n%d = %s.Length;" % (i, n))
                fixed.append("fixed (%s* _p%d = %s)" % (elem, i, n))
                call.append("_p%d" % i)
            elif r == "strings":
                sig.append("string[] %s" % n)
                pre.append("int _n%d = %s?.Length ?? 0;" % (i, n))
                pre.append("var _h%d = new IntPtr[_n%d];" % (i, i))
                pre.append("for (int k = 0; k < _n%d; ++k) _h%d[k] = Marshal.StringToCoTaskMemUTF8(%s[k]);" % (i, i, n))
                fixed.append("fixed (IntPtr* _p%d = _h%d)" % (i, i))
                call.append("(byte**)_p%d" % i)
                post.append("for (int k = 0; k < _n%d; ++k) Marshal.FreeCoTaskMem(_h%d[k]);" % (i, i))
            elif r == "out":
                elem = raw[:-1]
                sig.append("out %s %s" % (elem, n))
                fixed.append("fixed (%s* _p%d = &%s)" % (elem, i, n))
                pre.append("%s = default;" % n)
                call.append("_p%d" % i)
            elif r == "out_matrix":
                sig.append("float[] %s" % n)
                pre.append("if (%s == null || %s.Length < 16) throw new ArgumentException(\"16 floats expected\", nameof(%s));" % (n, n, n))
                fixed.append("fixed (float* _p%d = %s)" % (i, n))
                call.append("_p%d" % i)
            elif r == "out_string":
                sig.append("out string %s" % n)
                pre.append("byte* _s%d = null;" % i)
                call.append("&_s%d" % i)
                post.append("%s = FromUtf8(_s%d);" % (n, i))
            elif r == "out_struct":
                elem = raw[:-1]
                sig.append("out %s %s" % (elem, n))
                pre.append("%s = default;" % n)
                fixed.append("fixed (%s* _p%d = &%s)" % (elem, i, n))
                call.append("_p%d" % i)
            elif r == "callback":
                sig.append("%s %s" % (raw, n))
                key = '"%s"' % f.name
                ids = [cs_name(q.name) for q, rr in zip(f.params, roles) if rr == "value"]
                if ids:
                    key = '"%s:" + %s' % (f.name, ids[0])
                pre.append("lock (s_callbacks) { if (%s == null) s_callbacks.Remove(%s); else s_callbacks[%s] = %s; }" % (n, key, key, n))
                call.append(n)
            else:  # pointer
                sig.append("%s %s" % (raw, n))
                call.append(n)
        if f.variadic:
            sig.append("string text")
            pre.append("var _fmt = Utf8(\"%s\");")
            pre.append("var _txt = Utf8(text);")
            fixed.append("fixed (byte* _pf = _fmt)")
            fixed.append("fixed (byte* _pt = _txt)")
            call.append("_pt")
        ret = cs_type(api, f.ret)
        rt = api.resolve(f.ret)
        conv = None
        if rt.base == "char" and rt.pointers == 1:
            ret, conv = "string", "FromUtf8(_r)"
        name = strip_prefix(f.name)
        o.extend(xml_doc(f.doc, "        "))
        w("        public static %s %s(%s)" % (ret, name, ", ".join(sig)))
        w("        {")
        for l in pre:
            w("            " + l)
        indent = "            "
        for fx in fixed:
            w(indent + fx)
        if fixed:
            w(indent + "{")
            indent += "    "
        callexpr = "Native.%s(%s)" % (f.name, ", ".join(call))
        if f.ret.is_void():
            w(indent + callexpr + ";")
        else:
            w(indent + "var _r = " + callexpr + ";")
        for l in post:
            w(indent + l)
        if not f.ret.is_void():
            w(indent + "return %s;" % (conv or "_r"))
        if fixed:
            w("            }")
        w("        }")
        w("")
    w("    }")
    w("}")
    files["HRL.cs"] = "\n".join(o) + "\n"
    files["HRL.csproj"] = CSPROJ.format(version=api.version)
    return files


CSPROJ = """<Project Sdk="Microsoft.NET.Sdk">
  <!-- Generated by bindings/generate.py. -->
  <PropertyGroup>
    <TargetFrameworks>net6.0;net8.0</TargetFrameworks>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <Nullable>disable</Nullable>
    <RootNamespace>HRL</RootNamespace>
    <AssemblyName>HRL</AssemblyName>
    <Version>{version}.0</Version>
    <Description>C# bindings of the Horizon Rendering Library (P/Invoke, generated)</Description>
    <GenerateDocumentationFile>true</GenerateDocumentationFile>
  </PropertyGroup>
  <ItemGroup>
    <Compile Remove="examples/**" />
  </ItemGroup>
</Project>
"""
