def strip_prefix(name):
    """HRL_CreateScene -> CreateScene, HRL_GL_GetTextureGL_ID -> GL_GetTextureGL_ID"""
    return name[4:] if name.startswith("HRL_") else name


def snake(name):
    """HRL_CreateScene -> create_scene ; HRL_GL_GetTextureGL_ID -> gl_get_texture_gl_id"""
    n = strip_prefix(name)
    n = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", n)
    n = re.sub(r"([a-z])([A-Z])", r"\1_\2", n)
    n = re.sub(r"([0-9])([A-Z][a-z])", r"\1_\2", n)
    n = n.replace("__", "_").lower()
    return n


def camel(name):
    """camel case of a parameter : mesh_type -> meshType, _sceneid -> sceneid"""
    n = clean_name(name)
    parts = n.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def doc_lines(doc, width=None):
    if not doc:
        return []
    return [l.rstrip() for l in doc.splitlines()]


def size_param_of(roles, index):
    """For a bytes/array/strings parameter, index of its size parameter."""
    j = index + 1
    while j < len(roles):
        if roles[j] == "size":
            return j
        if roles[j] not in ("array",):
            return None
        j += 1
    return None


def sized_by(roles):
    """{size index: [indices of the buffers it measures]}"""
    out = {}
    for i, r in enumerate(roles):
        if r in ("bytes", "array", "strings"):
            s = size_param_of(roles, i)
            if s is not None:
                out.setdefault(s, []).append(i)
    return out


def enum_of(api, ctype):
    t = api.resolve(ctype)
    return api.enum(t.base)
