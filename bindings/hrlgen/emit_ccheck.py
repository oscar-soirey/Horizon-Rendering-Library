"""C program verifying the parsed API against the real headers.

Compile with a C11 compiler (warnings as errors on pointer types), e.g.
    cc -std=c11 -Werror=incompatible-pointer-types -I src -c bindings/c_check/hrl_abi_check.c
Every function signature, enum value, constant and struct field type of
hrl_api.json is checked; running it prints the struct layouts.
"""


def ctext(t, name="", role=None):
    if role == "strings" and t.const and t.pointers == 2 and t.base == "char":  # const char* const* (inner const not kept by the IR)
        return ("const char* const* " + name).strip()
    s = ("const " if t.const else "") + t.base + " " + "*" * t.pointers + name
    return s.strip()


def emit(api):
    o = []
    w = o.append
    w("/* Generated by bindings/generate.py. */")
    w("#define HRL_NO_DLL")
    w('#include "hrl.h"')
    w('#include "hrl_gl.h"')
    w('#include "hrl_vulkan.h"')
    w("#include <stddef.h>")
    w("#include <stdio.h>")
    w("")
    for e in api.enums:
        for n, v, _ in e.values:
            w("_Static_assert((long long)%s == %dLL, \"%s\");" % (n, v, n))
    for c in api.constants:
        if c.kind in ("int", "uint"):
            w("_Static_assert((unsigned long long)(%s) == (unsigned long long)(%dLL), \"%s\");" % (c.name, c.value, c.name))
    for s in api.structs:
        if s.opaque:
            continue
        for f in s.fields:
            n = "(%s)" % f.array if f.array else "1"
            w("_Static_assert(sizeof(((%s*)0)->%s) == sizeof(%s) * %s, \"%s.%s\");" % (s.name, f.name, ctext(f.type), n, s.name, f.name))
    w("")
    for f in api.functions:
        from .parser import param_roles
        params = ", ".join(ctext(p.type, "", r) for p, r in zip(f.params, param_roles(api, f))) or "void"
        if f.variadic:
            params += ", ..."
        w("static %s (*check_%s)(%s) = %s;" % (ctext(f.ret), f.name, params, f.name))
    for c in api.callbacks:
        params = ", ".join(ctext(p.type) for p in c.params) or "void"
        w("static %s (*check_cb_%s)(%s);" % (ctext(c.ret), c.name, params))
        w("static %s* check_cb_ptr_%s = &check_cb_%s;" % (c.name, c.name, c.name))
    w("")
    w("int main(void)")
    w("{")
    for s in api.structs:
        if s.opaque:
            continue
        w('    printf("%s %%zu\\n", sizeof(%s));' % (s.name, s.name))
        for f in s.fields:
            w('    printf("  %s %%zu\\n", offsetof(%s, %s));' % (f.name, s.name, f.name))
    w('    printf("functions %d\\n");' % len(api.functions))
    w("    return 0;")
    w("}")
    return "\n".join(o) + "\n"
