def _buffer(value):
    """bytes-like -> (pointer, size, keepalive)"""
    if value is None:
        return None, 0, None
    if isinstance(value, str):
        value = value.encode('utf-8')
    if isinstance(value, bytes):
        return ctypes.cast(ctypes.c_char_p(value), ctypes.c_void_p), len(value), value
    view = memoryview(value).cast('B')
    if view.readonly:
        data = bytes(view)
        return ctypes.cast(ctypes.c_char_p(data), ctypes.c_void_p), len(data), data
